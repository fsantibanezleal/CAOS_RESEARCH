"""EXP-067 addendum 1 (HWB-095): independent audit_v2.

Exact integers and Python bitsets only. The script does not import the producer
`run.py` as a library and does not read its results: it reads the (p, q) list of
`artifacts/results.json` and loads `run.py` only to observe the producer refuse
the noncoprime inputs of H6(b). The base semigroup comes from EXP-009's
`audit.py` (the loader the existing EXP-067 auditor uses) and is rebuilt here
from its generators.

Completeness of every comparison (tails are infinite). Write m for the
multiplicity, c for the conductor of Delta = m*N + q*Gamma and cG for the
conductor of Gamma.
  * Delta contains every integer >= c, so for a >= c the integers a, a + s',
    a + 2s' lie in Delta for any shift s' >= 0: E^(q) and D^(q) contain every
    a >= c.
  * E contains every a >= cG, and for x >= q*(cG + m) there is e >= cG with
    e = x * q^-1 (mod m) and e < cG + m, so x - q*e is a positive multiple of
    m: m*N + q*E and m*N + q*D contain every x >= q*(cG + m).
  * Every element of E^(q) is >= 0 and E^(q) contains all a >= c, so
    E^(q) + E^(q) contains every integer >= 2c.
With T = max(c, q*(cG + m)) all of E^(q), D^(q), their predictions and
E^(q) + E^(q) contain every integer >= 2T. Each comparison runs over [0, B]
with B = 2T + 2, which is at least "the conductor plus 2*q*s" of the addendum,
and the script also records that the tails inside the window are full.
Equality on [0, B] is therefore equality of the complete sets. Delta is
tabulated up to B + 2*(q*s + 1), the most any shifted membership test reads.

A non-gap shift and every other failure are recorded as fields, never raised.
Exit code 0 when every prediction holds, 1 with the failing case otherwise,
2 when an input is missing.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import math
import sys
from pathlib import Path
from types import ModuleType

ROOT = Path(__file__).resolve().parents[5]
HERE = Path(__file__).resolve().parent
RESULTS = HERE / "artifacts" / "results.json"
ARTIFACT = HERE / "artifacts" / "audit-v2.json"
EXP009_AUDIT = HERE.parent / "EXP-009-growing-interval-family" / "audit.py"
PRODUCER = HERE / "run.py"

P_RANGE = range(4, 13)
Q_PER_P = 8
ORIGINAL_NONCOPRIME = ((4, 2), (5, 3), (6, 2), (7, 7), (8, 2))
EXTRA_NONCOPRIME = ((9, 2), (10, 5), (11, 11), (12, 3), (4, 6))


def load_module(path: Path, name: str) -> ModuleType:
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def positions(bits: int) -> list[int]:
    """Indices of the set bits, ascending."""
    text = bin(bits)[:1:-1]
    return [index for index, char in enumerate(text) if char == "1"]


def window(limit: int) -> int:
    return (1 << (limit + 1)) - 1


def close_under(bits: int, step: int, limit: int) -> int:
    """Close a bitset under adding `step`, within [0, limit]."""
    mask = window(limit)
    bits &= mask
    shift = step
    while shift <= limit:
        bits |= (bits << shift) & mask
        shift *= 2
    return bits


def semigroup_bitset(generators: tuple[int, ...], limit: int) -> int:
    """Membership bitset of the semigroup generated by `generators`, up to limit."""
    bits = 1
    for generator in generators:
        bits = close_under(bits, generator, limit)
    return bits


def glued_bitset(multiplicity: int, q: int, base_bits: int, limit: int) -> int:
    """Membership bitset of m*N + q*Gamma up to `limit` (base_bits covers Gamma)."""
    scaled = 0
    for value in positions(base_bits):
        if q * value > limit:
            break
        scaled |= 1 << (q * value)
    return close_under(scaled, multiplicity, limit)


def transfer_bits(multiplicity: int, q: int, base_set_bits: int, limit: int) -> int:
    """The set m*N + q*S up to `limit`, for a base set S given as a bitset."""
    return glued_bitset(multiplicity, q, base_set_bits, limit)


def exponent_sets(bits: int, shift: int, limit: int) -> tuple[int, int]:
    """E = {a : a, a+s in S} and D = {a : a, a+s, a+2s in S} as bitsets on [0, limit]."""
    mask = window(limit)
    e_bits = bits & (bits >> shift) & mask
    d_bits = e_bits & (bits >> (2 * shift))
    return e_bits, d_bits


def sumset(bits: int, limit: int) -> int:
    """S + S restricted to [0, limit]."""
    mask = window(limit)
    result = 0
    for value in positions(bits & mask):
        result |= (bits << value) & mask
    return result


def minimal_generators(bits: int, limit: int) -> list[int]:
    """Nonzero elements that are not a sum of two nonzero elements (within limit)."""
    mask = window(limit)
    nonzero = bits & mask & ~1
    sums = 0
    for value in positions(nonzero):
        sums |= (nonzero << value) & mask
    return positions(nonzero & ~sums)


def first_difference(left: int, right: int) -> int | None:
    diff = left ^ right
    return (diff & -diff).bit_length() - 1 if diff else None


def frobenius_of(bits: int, limit: int, multiplicity: int) -> int | None:
    """Largest gap, checked closed: `multiplicity` consecutive members sit above it."""
    gaps = [value for value in range(limit + 1) if not bits >> value & 1]
    frobenius = max(gaps) if gaps else -1
    top = range(frobenius + 1, frobenius + multiplicity + 1)
    if frobenius + multiplicity > limit or not all(bits >> value & 1 for value in top):
        return None
    return frobenius


def shift_record(
    delta_bits: int, shift: int, bound: int, conductor: int, with_tail: bool
) -> dict[str, object]:
    e_bits, d_bits = exponent_sets(delta_bits, shift, bound)
    sums = sumset(e_bits, bound)
    record: dict[str, object] = {
        "shift": shift,
        "shift_in_semigroup": bool(delta_bits >> shift & 1),
        "e_size": e_bits.bit_count(),
        "d_size": d_bits.bit_count(),
        "rigid": sums == d_bits,
        "first_sumset_difference": first_difference(sums, d_bits),
    }
    if with_tail:
        record["tail_e_full"] = all(e_bits >> a & 1 for a in range(conductor, bound + 1))
        record["tail_d_full"] = all(d_bits >> a & 1 for a in range(conductor, bound + 1))
        record["tail_sum_full"] = all(
            sums >> a & 1 for a in range(2 * conductor, bound + 1)
        )
    return record


def audit_case(
    p: int, q: int, base_gens: tuple[int, ...], base_frob: int
) -> dict[str, object]:
    multiplicity = 24 * p
    base_shift = 6 * p
    base_conductor = base_frob + 1
    scaled = q * base_shift

    # Conductor of Delta from a first tabulation, closed by m consecutive members.
    first_limit = q * (base_frob + 2 * multiplicity) + multiplicity
    first_base = semigroup_bitset(base_gens, first_limit // q + 1)
    first_bits = glued_bitset(multiplicity, q, first_base, first_limit)
    frobenius = frobenius_of(first_bits, first_limit, multiplicity)
    if frobenius is None:
        return {
            "p": p,
            "q": q,
            "accepted": False,
            "failures": ["Frobenius number not closed"],
        }
    conductor = frobenius + 1

    tail = max(conductor, q * (base_conductor + multiplicity))
    bound = 2 * tail + 2
    limit = bound + 2 * (scaled + 1)
    base_limit = limit // q + 2 * base_shift + 2
    base_bits = semigroup_bitset(base_gens, base_limit)
    delta_bits = glued_bitset(multiplicity, q, base_bits, limit)

    # H1: E and D recomputed on Delta and compared with m*N + q*E, m*N + q*D.
    e_actual, d_actual = exponent_sets(delta_bits, scaled, bound)
    e_base, d_base = exponent_sets(base_bits, base_shift, bound // q + 1)
    e_predicted = transfer_bits(multiplicity, q, e_base, bound)
    d_predicted = transfer_bits(multiplicity, q, d_base, bound)
    e_equal = e_actual == e_predicted
    d_equal = d_actual == d_predicted

    # H2: D = E + E on the recomputed sets (and on the predicted ones).
    main = shift_record(delta_bits, scaled, bound, conductor, True)
    sum_of_predicted = sumset(e_predicted, bound)

    # H4: minimal generators of Delta (all lie below F + m).
    generators = minimal_generators(delta_bits, frobenius + multiplicity)

    # H5: the shift is a gap (a field, never an exception).
    shift_is_gap = not delta_bits >> scaled & 1

    # H6(c): the perturbed shift q*s + 1, data only.
    perturbed = shift_record(delta_bits, scaled + 1, bound, conductor, False)

    tails_ok = bool(
        main["tail_e_full"]
        and main["tail_d_full"]
        and main["tail_sum_full"]
        and all(e_predicted >> a & 1 for a in range(tail, bound + 1))
        and all(d_predicted >> a & 1 for a in range(tail, bound + 1))
    )
    h1 = e_equal and d_equal and tails_ok
    h2 = bool(main["rigid"]) and sum_of_predicted == d_predicted
    h4 = len(generators) == 11 * p
    failures = [
        name
        for name, ok in (
            ("H1 E/D transfer", h1),
            ("H2 rigidity", h2),
            ("H4 embedding dimension", h4),
            ("H5 shift is a gap", shift_is_gap),
        )
        if not ok
    ]
    return {
        "p": p,
        "q": q,
        "multiplicity": multiplicity,
        "scaled_shift": scaled,
        "frobenius": frobenius,
        "conductor": conductor,
        "comparison_bound": bound,
        "positions_compared": bound + 1,
        "h1_e_equal": e_equal,
        "h1_d_equal": d_equal,
        "h1_tails_full": tails_ok,
        "h1_e_size": e_actual.bit_count(),
        "h1_d_size": d_actual.bit_count(),
        "h1_first_e_difference": first_difference(e_actual, e_predicted),
        "h1_first_d_difference": first_difference(d_actual, d_predicted),
        "h2_rigid": h2,
        "h2_first_sumset_difference": main["first_sumset_difference"],
        "h4_embedding_dimension": len(generators),
        "h4_expected": 11 * p,
        "h5_shift_is_gap": shift_is_gap,
        "h6c_perturbed": perturbed,
        "accepted": not failures,
        "failures": failures,
    }


def base_record(p: int, exp009: ModuleType) -> dict[str, object]:
    """H3: the base semigroup rebuilt from its generators against EXP-009's mask."""
    mask, frobenius, generators = exp009.independent_mask(p)
    extent = frobenius + 2 * 24 * p
    rebuilt = semigroup_bitset(tuple(generators), extent)
    reference = mask | (window(extent) & ~window(frobenius))  # every integer above F
    return {
        "p": p,
        "frobenius": frobenius,
        "positions_compared": extent + 1,
        "mask_equal": rebuilt == reference,
        "first_difference": first_difference(rebuilt, reference),
        "frobenius_is_gap": not rebuilt >> frobenius & 1,
        "generator_count": len(generators),
    }


def control_45(q: int) -> dict[str, object]:
    """H6(a): Gamma = <4,5>, s = 1, glued with q; expected nonrigid at shift q."""
    multiplicity = 4
    first_limit = 4 * q * 8 + 200
    first_base = semigroup_bitset((4, 5), first_limit // q + 1)
    first_bits = glued_bitset(multiplicity, q, first_base, first_limit)
    frobenius = frobenius_of(first_bits, first_limit, multiplicity)
    if frobenius is None:
        return {"q": q, "nonrigid": False, "shift_is_gap": False}
    conductor = frobenius + 1
    bound = 2 * max(conductor, q * (2 + multiplicity)) + 2
    limit = bound + 2 * q + 2
    base_bits = semigroup_bitset((4, 5), limit // q + 4)
    delta_bits = glued_bitset(multiplicity, q, base_bits, limit)
    record = shift_record(delta_bits, q, bound, conductor, False)
    return {
        "q": q,
        "shift": q,
        "frobenius": frobenius,
        "shift_is_gap": not record["shift_in_semigroup"],
        "nonrigid": not record["rigid"],
        "first_sumset_difference": record["first_sumset_difference"],
    }


def noncoprime_record(p: int, q: int) -> dict[str, object]:
    """H6(b): gcd of the generators, an integer above the bound outside the set,
    and the producer's refusal observed by calling it."""
    multiplicity = 24 * p
    exp009 = load_module(EXP009_AUDIT, "exp009_audit_v2_noncoprime")
    _, base_frob, base_gens = exp009.independent_mask(p)
    generators = (multiplicity,) + tuple(q * v for v in base_gens if v != multiplicity)
    divisor = 0
    for value in generators:
        divisor = math.gcd(divisor, value)
    proposed_bound = q * (base_frob + multiplicity)
    witness = 2 * proposed_bound + 1
    while divisor > 1 and witness % divisor == 0:
        witness += 1
    limit = witness + 2 * multiplicity
    base_bits = semigroup_bitset(tuple(base_gens), limit // q + 1)
    delta_bits = glued_bitset(multiplicity, q, base_bits, limit)
    stray = [value for value in positions(delta_bits) if value % divisor != 0]
    producer = load_module(PRODUCER, "exp067_producer_refusal_probe")
    try:
        producer.case_record(p, q)
        refused, error_type, error = False, "", ""
    except Exception as exc:  # the refusal is the observation
        refused, error_type, error = True, type(exc).__name__, str(exc)
    return {
        "p": p,
        "q": q,
        "multiplicity": multiplicity,
        "gcd_pair": math.gcd(multiplicity, q),
        "generator_gcd": divisor,
        "gcd_exceeds_one": divisor > 1,
        "proposed_bound": proposed_bound,
        "witness": witness,
        "witness_above_bound": witness > proposed_bound,
        "witness_not_in_semigroup": not delta_bits >> witness & 1,
        "elements_not_divisible_by_gcd": len(stray),
        "producer_refused": refused,
        "producer_error_type": error_type,
        "producer_error": error,
    }


def producer_accepts_coprime() -> bool:
    """The refusal is specific: the producer accepts a coprime pair."""
    producer = load_module(PRODUCER, "exp067_producer_acceptance_probe")
    return bool(producer.case_record(4, 5)["accepted"])


def first_q_values(multiplicity: int, count: int = Q_PER_P) -> tuple[int, ...]:
    values: list[int] = []
    q = 1
    while len(values) < count:
        if math.gcd(q, multiplicity) == 1:
            values.append(q)
        q += 1
    return tuple(values)


def main() -> int:
    for path in (EXP009_AUDIT, RESULTS, PRODUCER):
        if not path.exists():
            print(f"missing input: {path}", file=sys.stderr)
            return 2
    exp009 = load_module(EXP009_AUDIT, "exp009_audit_v2")
    source = json.loads(RESULTS.read_text(encoding="utf-8"))
    source_pairs = [(case["p"], case["q"]) for case in source["cases"]]
    own_pairs = [(p, q) for p in P_RANGE for q in first_q_values(24 * p)]

    bases = {p: base_record(p, exp009) for p in P_RANGE}
    cases: list[dict[str, object]] = []
    for p in P_RANGE:
        _, base_frob, base_gens = exp009.independent_mask(p)
        for q in first_q_values(24 * p):
            cases.append(audit_case(p, q, tuple(base_gens), base_frob))
        print(f"audit_v2 p={p}: {Q_PER_P} cases", flush=True)

    controls_a = [control_45(q) for q in (1, 3, 5, 7)]
    controls_b = [
        noncoprime_record(p, q) for p, q in ORIGINAL_NONCOPRIME + EXTRA_NONCOPRIME
    ]
    coprime_accepted = producer_accepts_coprime()

    h3 = all(bool(b["mask_equal"]) for b in bases.values())
    h6a = all(bool(c["nonrigid"]) and bool(c["shift_is_gap"]) for c in controls_a)
    h6b = coprime_accepted and all(
        bool(c["gcd_exceeds_one"])
        and bool(c["witness_above_bound"])
        and bool(c["witness_not_in_semigroup"])
        and c["elements_not_divisible_by_gcd"] == 0
        and bool(c["producer_refused"])
        for c in controls_b
    )
    summary = {
        "case_list_matches_producer": source_pairs == own_pairs,
        "case_count": len(cases),
        "H1": sum(
            1
            for c in cases
            if c.get("h1_e_equal") and c.get("h1_d_equal") and c.get("h1_tails_full")
        ),
        "H2": sum(1 for c in cases if c.get("h2_rigid")),
        "H3": sum(1 for b in bases.values() if b["mask_equal"]),
        "H4": sum(
            1 for c in cases if c.get("h4_embedding_dimension") == c.get("h4_expected")
        ),
        "H5": sum(1 for c in cases if c.get("h5_shift_is_gap")),
        "H6a": sum(1 for c in controls_a if c["nonrigid"]),
        "H6b": sum(
            1 for c in controls_b if c["producer_refused"] and c["gcd_exceeds_one"]
        ),
        "H6c_perturbed_rigid": sum(
            1 for c in cases if c.get("h6c_perturbed", {}).get("rigid")
        ),
        "H6c_perturbed_gap": sum(
            1
            for c in cases
            if c.get("h6c_perturbed", {}).get("shift_in_semigroup") is False
        ),
    }
    accepted = bool(
        summary["case_list_matches_producer"]
        and all(bool(c["accepted"]) for c in cases)
        and h3
        and h6a
        and h6b
    )
    canonical = json.dumps(cases, sort_keys=True, separators=(",", ":"))
    artifact = {
        "experiment": "EXP-067",
        "addendum": 1,
        "method": "membership bitsets of Delta, recomputed E and D, direct sumsets, "
        "minimal generators, rerun controls",
        "summary": summary,
        "cases": cases,
        "base_semigroups": [bases[p] for p in P_RANGE],
        "controls_h6a": controls_a,
        "controls_h6b": controls_b,
        "producer_accepts_coprime_pair": coprime_accepted,
        "case_aggregate_sha256": hashlib.sha256(canonical.encode("utf-8")).hexdigest(),
        "accepted": accepted,
    }
    ARTIFACT.parent.mkdir(parents=True, exist_ok=True)
    ARTIFACT.write_text(
        json.dumps(artifact, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"audit_v2 wrote {ARTIFACT.relative_to(ROOT)}", flush=True)
    for case in cases:
        if not case["accepted"]:
            print(f"FAIL p={case['p']} q={case['q']}: {case['failures']}", flush=True)
    print(f"audit_v2 summary {json.dumps(summary, sort_keys=True)}", flush=True)
    print(f"audit_v2 accepted={accepted}", flush=True)
    return 0 if accepted else 1


if __name__ == "__main__":
    raise SystemExit(main())
