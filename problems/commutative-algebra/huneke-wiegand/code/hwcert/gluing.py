"""Exact relative-ideal arithmetic for gluings of numerical semigroups (EXP-068).

Sets of integers are bit masks over a window [lo, hi); every integer >= hi is implicitly a member,
so every set handled here must contain a full tail inside the window (checked by `require_tail`).
Semigroups are passed with any generating set: Gamma minus 0 is the union of g + Gamma over the
generators, which is all that minimal generation and the tensor relations need.

Two independent routes decide torsion in I_A (x) I_(A*): the direct tensor computation (connected
components of the monomial relation graph, degree by degree) and the partition criterion (Leamer,
Theorem 1.4; García-Sánchez and Leamer, Remark 3).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from itertools import combinations
from math import gcd


@dataclass(frozen=True)
class Window:
    lo: int
    hi: int

    @property
    def width(self) -> int:
        return self.hi - self.lo

    @property
    def full(self) -> int:
        return (1 << self.width) - 1

    def bit(self, value: int) -> int:
        return 1 << (value - self.lo)

    def members(self, mask: int) -> list[int]:
        out = []
        while mask:
            low = mask & -mask
            out.append(self.lo + low.bit_length() - 1)
            mask ^= low
        return out

    def first(self, mask: int) -> int:
        return self.lo + (mask & -mask).bit_length() - 1

    def contains(self, mask: int, value: int) -> bool:
        if value >= self.hi:
            return True
        if value < self.lo:
            return False
        return bool(mask >> (value - self.lo) & 1)

    def shift(self, mask: int, p: int) -> int:
        """Mask of {x + p : x in the set}; the implicit tail above hi supplies the new top bits."""
        if p >= 0:
            return (mask << p) & self.full
        q = -p
        return (mask >> q) | (((1 << q) - 1) << (self.width - q))

    def tail_start(self, mask: int) -> int:
        """Least c with [c, hi) inside the set; equals hi when the window holds no full tail."""
        inverse = ~mask & self.full
        return self.lo if inverse == 0 else self.lo + inverse.bit_length()

    def require_tail(self, mask: int, margin: int, label: str) -> None:
        if self.tail_start(mask) + margin > self.hi:
            raise ValueError(f"window too small for {label}: tail starts at {self.tail_start(mask)}")

    def from_values(self, values) -> int:
        mask = 0
        for v in values:
            if v < self.lo:
                raise ValueError(f"value {v} below window")
            if v < self.hi:
                mask |= self.bit(v)
        return mask


def semigroup_mask(window: Window, generators: tuple[int, ...]) -> int:
    """Mask of the numerical semigroup generated by positive integers with gcd 1."""
    if gcd(*generators) != 1:
        raise ValueError("generators must have gcd 1")
    if window.lo > 0:
        raise ValueError("window must contain 0")
    mask = window.bit(0)
    for value in range(1, window.hi):
        for g in generators:
            if value - g >= 0 and mask >> (value - g - window.lo) & 1:
                mask |= window.bit(value)
                break
    window.require_tail(mask, max(generators), "semigroup")
    return mask


def ideal_from_generators(window: Window, semigroup: int, generators: tuple[int, ...]) -> int:
    mask = 0
    for g in generators:
        mask |= window.shift(semigroup, g)
    return mask


def minimal_generators(window: Window, ideal: int, semigroup_gens: tuple[int, ...]) -> tuple[int, ...]:
    """Minimal generators of a relative ideal: its elements outside ideal + (Gamma minus 0)."""
    covered = 0
    for g in semigroup_gens:
        covered |= window.shift(ideal, g)
    return tuple(window.members(ideal & ~covered))


def dual(window: Window, semigroup: int, ideal_gens: tuple[int, ...]) -> int:
    """A* = Gamma - A, the intersection over generators x of (Gamma - x)."""
    mask = window.full
    for x in ideal_gens:
        mask &= window.shift(semigroup, -x)
    return mask


def ideal_sum(window: Window, left_gens: tuple[int, ...], right: int) -> int:
    mask = 0
    for p in left_gens:
        mask |= window.shift(right, p)
    return mask


def is_huneke_wiegand(window: Window, semigroup: int, semigroup_gens: tuple[int, ...],
                      ideal_gens: tuple[int, ...]) -> bool | None:
    """Partition criterion: None for a principal ideal; True iff some partition breaks equality."""
    gens = minimal_generators(window, ideal_from_generators(window, semigroup, ideal_gens), semigroup_gens)
    if len(gens) == 1:
        return None
    star = dual(window, semigroup, gens)
    window.require_tail(star, max(gens) - min(gens), "dual")
    first, rest = gens[0], gens[1:]
    for size in range(0, len(rest)):
        for chosen in combinations(rest, size):
            p_gens = (first,) + chosen
            q_gens = tuple(x for x in rest if x not in chosen)
            p_mask = ideal_from_generators(window, semigroup, p_gens)
            q_mask = ideal_from_generators(window, semigroup, q_gens)
            left = ideal_sum(window, p_gens, star) & ideal_sum(window, q_gens, star)
            meet_gens = minimal_generators(window, p_mask & q_mask, semigroup_gens)
            right = ideal_sum(window, meet_gens, star)
            if left != right:
                return True
    return False


class _UnionFind:
    def __init__(self) -> None:
        self.parent: dict[tuple[int, int], tuple[int, int]] = {}

    def find(self, item: tuple[int, int]) -> tuple[int, int]:
        root = item
        while self.parent.get(root, root) != root:
            root = self.parent[root]
        while item != root:
            nxt = self.parent.get(item, item)
            self.parent[item] = root
            item = nxt
        return root

    def union(self, a: tuple[int, int], b: tuple[int, int]) -> None:
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.parent[ra] = rb


@dataclass
class TensorTorsion:
    length: int
    jordan_at_least: dict[int, int] = field(default_factory=dict)  # j -> blocks of size >= j


def tensor_torsion(window: Window, semigroup: int, semigroup_gens: tuple[int, ...], ideal_gens: tuple[int, ...],
                   y_degree: int | None = None) -> TensorTorsion:
    """Torsion of I_A (x) I_(A*) from the definition, and the Jordan type of t^y_degree acting on it.

    In degree d the module is spanned by e_x (x) e_z (x in A, z in A*, x + z = d) modulo
    e_(x+g) (x) e_z = e_x (x) e_(z+g) for generators g; its dimension is the number of connected
    components, and the image in I_A I_(A*) is one-dimensional, so the torsion in degree d has
    dimension components - 1. Every pair joins an anchor (x_i, d - x_i) with x_i a generator of A, and
    two anchors join through (w, d - w) with w = max generator + c(Gamma) once d - w >= c(A*); hence the
    torsion vanishes for d >= maxgen(A) + c(Gamma) + c(A*), where the scan stops.
    """
    ideal = ideal_from_generators(window, semigroup, ideal_gens)
    gens = minimal_generators(window, ideal, semigroup_gens)
    star = dual(window, semigroup, gens)
    conductor = window.tail_start(semigroup)
    star_conductor = window.tail_start(star)
    window.require_tail(star, 1, "dual")
    top = max(gens) + conductor + star_conductor
    a_min, s_min = window.first(ideal), window.first(star)
    finder = _UnionFind()
    degrees: dict[int, list[tuple[int, int]]] = {}
    for d in range(a_min + s_min, top + 1):
        pairs = [(x, d - x) for x in range(a_min, d - s_min + 1)
                 if window.contains(ideal, x) and window.contains(star, d - x)]
        degrees[d] = pairs
        for x, z in pairs:
            for g in semigroup_gens:
                if window.contains(ideal, x - g):
                    finder.union((x, z), (x - g, z + g))
    roots = {d: {finder.find(p): p for p in pairs} for d, pairs in degrees.items()}
    length = sum(max(0, len(r) - 1) for r in roots.values())
    jordan: dict[int, int] = {}
    if y_degree is not None and length:
        def rank(power: int) -> int:
            total, shift = 0, power * y_degree
            for d, reps in roots.items():
                if len(reps) <= 1 or d + shift > top:
                    continue
                images = {finder.find((x + shift, z)) for x, z in reps.values()}
                total += len(images) - 1
            return total
        ranks = [length]
        while ranks[-1] > 0:
            ranks.append(rank(len(ranks)))
        jordan = {j: ranks[j - 1] - ranks[j] for j in range(1, len(ranks))}
    return TensorTorsion(length=length, jordan_at_least=jordan)


def glue_generators(a1: int, gens1: tuple[int, ...], a2: int, gens2: tuple[int, ...]) -> tuple[int, ...]:
    return tuple(sorted({a1 * g for g in gens1} | {a2 * g for g in gens2}))


def extension_generators(a1: int, gens1: tuple[int, ...], a2: int, gens2: tuple[int, ...]) -> tuple[int, ...]:
    """Lemma 8(1): a1*A1 + a2*A2 is generated by a1*x + a2*z over pairs of generators."""
    return tuple(sorted({a1 * x + a2 * z for x in gens1 for z in gens2}))


def predicted_length(a1: int, a2: int, t1: TensorTorsion, t2: TensorTorsion) -> int:
    """EXP-068 item 1, with y acting as t^a2 on the first factor and t^a1 on the second."""
    keys = set(t1.jordan_at_least) | set(t2.jordan_at_least)
    cross = sum(t1.jordan_at_least.get(j, 0) * t2.jordan_at_least.get(j, 0) for j in keys)
    return a1 * t1.length + a2 * t2.length + cross


def hilbert_identity_holds(window: Window, glued: int, a1: int, a2: int, ideal1: int, w1: Window,
                           ideal2: int, w2: Window, ideal: int, upto: int) -> bool:
    """Coefficientwise H_A(z) = H_A1(z^a1) H_A2(z^a2) (1 - z^(a1*a2)) for degrees below `upto`."""
    e1 = [x for x in w1.members(ideal1)] + list(range(w1.hi, upto // a1 + 2))
    e2 = [z for z in w2.members(ideal2)] + list(range(w2.hi, upto // a2 + 2))
    counts: dict[int, int] = {}
    for x in e1:
        for z in e2:
            d = a1 * x + a2 * z
            if d < upto:
                counts[d] = counts.get(d, 0) + 1
    low = min(counts) if counts else 0
    for d in range(low, upto):
        coefficient = counts.get(d, 0) - counts.get(d - a1 * a2, 0)
        if coefficient != (1 if window.contains(ideal, d) else 0):
            return False
    return True


def is_extension(window: Window, glued: int, glued_gens: tuple[int, ...], ideal: int, a1: int, a2: int,
                 sg1: int, w1: Window, gens1: tuple[int, ...], sg2: int, w2: Window, gens2: tuple[int, ...]) -> bool:
    """Whether a relative ideal of the gluing equals a1*B1 + a2*B2 up to translation.

    By Lemma 8(5) the multiples of a1 (of a2) in an extension are a translate of a1*A1 (of a2*A2), so
    the candidate factors are read off and the extension they generate is compared with the ideal.
    """
    elems = window.members(ideal)
    b1 = [x // a1 for x in elems if x % a1 == 0] + list(range(window.hi // a1, w1.hi))
    b2 = [z // a2 for z in elems if z % a2 == 0] + list(range(window.hi // a2, w2.hi))
    b1_mask, b2_mask = w1.from_values(b1), w2.from_values(b2)
    if (ideal_sum(w1, gens1, b1_mask) | b1_mask) != b1_mask or (ideal_sum(w2, gens2, b2_mask) | b2_mask) != b2_mask:
        return False
    g1 = minimal_generators(w1, b1_mask, gens1)
    g2 = minimal_generators(w2, b2_mask, gens2)
    rebuilt = ideal_from_generators(window, glued, extension_generators(a1, g1, a2, g2))
    shift = window.first(rebuilt) - window.first(ideal)
    return window.shift(rebuilt, -shift) == ideal
