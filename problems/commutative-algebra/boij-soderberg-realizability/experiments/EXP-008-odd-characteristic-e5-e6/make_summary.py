"""EXP-008: totals per family, the three predictions as counts, and results-summary.md, all from results.json.

Every number of results-summary.md is computed from the chunk records of artifacts/results.json.  Counts and pairs only:
no statement about realizability is made here (the coordinating session draws the conclusions).
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import exp008_routine as X  # noqa: E402
from exp008_routine import R  # noqa: E402


def _merge(dst, src):
    for k, v in src.items():
        dst[k] = dst.get(k, 0) + v


def compute_totals(res):
    out = {}
    for fam, (e, fname, planned, chunk) in X.FAMILIES.items():
        recs = [c for c in res["chunks"].values() if c["family"] == fam]
        q = int(fname[3:-1])
        tgt = R.target_rank(e)
        h3 = R.h_e(e, 3 * e)
        t = {"family": fam, "e": e, "field": fname, "q": q, "planned": planned, "chunks": len(recs),
             "chunks_planned": len(range(0, planned, chunk)), "spaces": sum(c["n"] for c in recs), "rank_hist": {},
             "hilbert_computed": 0, "hilbert_other": {}, "pure_hilbert": sum(c["pure_hilbert"] for c in recs),
             "pure": sum(c["pure"] for c in recs), "nonpure_tables": {}, "target_rank": tgt, "h_e_3e": h3,
             "seconds_cpu": round(sum(c["seconds"] for c in recs), 1),
             "seconds_wall": res.get("family_wall_seconds", {}).get(fam)}
        for c in recs:
            _merge(t["rank_hist"], c["rank_hist"])
            _merge(t["hilbert_other"], c["hilbert_other"])
            _merge(t["nonpure_tables"], c["nonpure_tables"])
            t["hilbert_computed"] += c["hilbert_computed"]
        t["rank_hist"] = {k: t["rank_hist"][k] for k in sorted(t["rank_hist"], key=int)}
        t["rank_eq_target"] = t["rank_hist"].get(str(tgt), 0)
        t["rank_above_target"] = sum(v for k, v in t["rank_hist"].items() if int(k) > tgt)
        n = t["spaces"]
        t["q_pow"] = "q^(-%d)" % (2 * h3)
        t["q_minus_2h"] = float(q) ** (-2 * h3)
        t["share_rank_eq_target"] = t["rank_eq_target"] / n if n else None
        t["share_pure_hilbert"] = t["pure_hilbert"] / n if n else None
        t["share_pure"] = t["pure"] / n if n else None
        t["ratio_pure_to_q"] = t["share_pure"] / t["q_minus_2h"] if n else None
        t["upper_bound_3_over_n"] = 3.0 / n if n and t["pure"] == 0 else None
        t["complete"] = n == planned
        t["stopped_early"] = t["pure"] >= X.EARLY_STOP and n < planned
        out[fam] = t
    return out


def predictions(totals):
    """P1 to P3: pure spaces found in the family (counts only)."""
    p = {}
    for name, fam in (("P1", "A"), ("P2", "B"), ("P3", "C")):
        t = totals[fam]
        p[name] = {"family": fam, "field": t["field"], "e": t["e"], "spaces": t["spaces"], "pure": t["pure"], "holds": t["pure"] > 0}
    p["P1_and_P2_hold"] = p["P1"]["holds"] and p["P2"]["holds"]
    return p


def totals_text(totals):
    lines = ["%-4s %-3s %-8s %9s %9s %9s %8s %8s %7s" % ("fam", "e", "field", "spaces", "planned", "rank=tgt", "pureHF", "pure", "early")]
    for t in totals.values():
        lines.append("%-4s %-3d %-8s %9d %9d %9d %8d %8d %7s" % (t["family"], t["e"], t["field"], t["spaces"], t["planned"],
                                                               t["rank_eq_target"], t["pure_hilbert"], t["pure"], t["stopped_early"]))
    return "\n".join(lines)


def _pct(x, d=4):
    return "n/a" if x is None else "%.*f%%" % (d, 100 * x)


def _table_text(rows):
    return "none" if rows is None else "; ".join("b_%d,%d = %d" % tuple(r) for r in rows)


def _space(res, fam, index):
    for c in res["chunks"].values():
        if c["family"] == fam and c["start"] <= index < c["end"]:
            for sp in c["spaces"]:
                if sp["index"] == index:
                    return sp
    return None


def write_summary(res, path):
    T, P = res["totals"], res["predictions"]
    L = ["# EXP-008 results summary", "",
         "Generated by make_summary.py from artifacts/results.json; every number below is computed, none is typed.",
         "Hypothesis: hypothesis.md (frozen). Counts and pairs only: no statement of realizability is made here.", "", "## Gates", ""]
    for g in ("G1", "G2", "G3"):
        r = res["gates"].get(g)
        if r is None:
            L.append("- %s: not run" % g)
        elif r.get("blocked"):
            L.append("- %s: BLOCKED, %s" % (g, r["reason"]))
        else:
            extra = ""
            if g == "G2":
                extra = " (%s; %d pure spaces in the sample, %d with the same pure table from both instruments)" % (
                    r["singular"], r["sample_spaces"], r["agree_and_pure_in_I2"])
            if g == "G3":
                extra = " (%s)" % r["last_line"]
            if g == "G1":
                extra = " (%d cases)" % len(r["cases"])
            L.append("- %s: %s%s" % (g, "PASSED" if r["passed"] else "FAILED", extra))
    L += ["", "## Totals per family", "",
          "| Family | e | Field | Spaces done / planned | Early stop | rank mu_3e = target | Pure Hilbert function | Pure (Betti table) | Share pure | q^(-2 h_e(3e)) | Share / q^(-2 h_e(3e)) | CPU s | Wall s |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for t in T.values():
        L.append("| %s | %d | %s | %d / %d | %s | %d (%s) | %d | %d | %s | %s = %s | %s | %s | %s |" % (
            t["family"], t["e"], t["field"], t["spaces"], t["planned"], "yes" if t["stopped_early"] else "no", t["rank_eq_target"],
            _pct(t["share_rank_eq_target"]), t["pure_hilbert"], t["pure"], _pct(t["share_pure"], 5), t["q_pow"],
            _pct(t["q_minus_2h"], 5), "n/a" if t["ratio_pure_to_q"] is None else "%.3f" % t["ratio_pure_to_q"],
            t["seconds_cpu"], t["seconds_wall"]))
    L += ["", "The target rank of mu_3e(W) is r = 2 u(2e) - 2: %s. Every share is stated over the spaces done." % ", ".join(
        "%d (e = %d)" % (t["target_rank"], t["e"]) for t in {x["e"]: x for x in T.values()}.values()), ""]
    for t in T.values():
        if t["pure"] == 0:
            L.append("- Family %s: no pure space among %d; upper bound of the hypothesis, 3 / %d = %.3g." % (
                t["family"], t["spaces"], t["spaces"], 3.0 / t["spaces"] if t["spaces"] else float("nan")))
    L += ["", "## Distribution of rank mu_3e per family", ""]
    for t in T.values():
        L.append("- %s (e = %d, %s): %s" % (t["family"], t["e"], t["field"], ", ".join("%s: %d" % kv for kv in t["rank_hist"].items())))
    L += ["", "## Spaces with the pure Hilbert function but another Betti table", ""]
    for t in T.values():
        n_np = sum(t["nonpure_tables"].values())
        L.append("- %s: %d of %d spaces with the pure Hilbert function have another table (%d distinct)" % (t["family"], n_np, t["pure_hilbert"], len(t["nonpure_tables"])))
        for k, v in sorted(t["nonpure_tables"].items(), key=lambda kv: -kv[1])[:3]:
            L.append("    - %d x %s" % (v, k))
    L += ["", "## Spaces with rank mu_3e at the target and a Hilbert function other than h_e", ""]
    for t in T.values():
        L.append("- %s: Hilbert function computed for %d spaces; %d with a function other than h_e (%d distinct)" % (
            t["family"], t["hilbert_computed"], sum(t["hilbert_other"].values()), len(t["hilbert_other"])))
    L += ["", "## Predictions as counts", ""]
    for name in ("P1", "P2", "P3"):
        p = P[name]
        L.append("- %s (family %s, e = %d, %s): %d pure spaces among %d spaces done; pure spaces found in the family: %s." % (
            name, p["family"], p["e"], p["field"], p["pure"], p["spaces"], p["holds"]))
    L.append("- P1 and P2 both found a pure space: %s." % P["P1_and_P2_hold"])
    L += ["", "## Explicit pure pairs (basis of W, PBW monomials x^i y^j z^k; yx = xy - z)", ""]
    g2 = res["gates"].get("G2", {}).get("rows", [])
    shown = {}
    for r in g2:
        if shown.get(r["family"], 0) >= 3 or not r.get("agree"):
            continue
        sp = _space(res, r["family"], r["index"])
        if sp is None or "basis" not in sp:
            continue
        shown[r["family"]] = shown.get(r["family"], 0) + 1
        F = R.make_field(r["field"])
        L.append("- %s over %s, e = %d, seed %d: f = %s ; g = %s ; Betti table, uhlib: %s ; Singular: %s" % (
            r["family"], r["field"], X.FAMILIES[r["family"]][0], sp["seed"], R.poly_text(F, sp["basis"][0]),
            R.poly_text(F, sp["basis"][1]), _table_text(r["betti_I1"]), _table_text(r["betti_I2"])))
    if not g2:
        L.append("- G2 has not been run")
    L += ["", "Wall time of the commands: " + ", ".join(
        "%s%s %.0f s" % (r["command"], " " + r["family"] if "family" in r else "", r["seconds"]) for r in res["runs"])
          + "; total %.0f s." % res.get("wall_seconds_total", 0), ""]
    Path(path).write_text("\n".join(L), encoding="utf-8", newline="\n")
