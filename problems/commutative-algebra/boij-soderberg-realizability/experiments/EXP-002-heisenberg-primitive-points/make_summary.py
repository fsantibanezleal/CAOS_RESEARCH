"""Write results-summary.md from artifacts/results.json (run run.py first). Facts only, no verdict language."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = json.loads((HERE / "artifacts" / "results.json").read_text(encoding="utf-8"))
C = R["claims"]
out = []


def w(s=""):
    out.append(s)


def tab(rows):
    return " ".join("(%d,%d,%d)" % tuple(r) for r in rows) if rows else "none"


def hf(rec):
    h = rec["hilbert_function"]
    return "(" + ",".join(str(n) for n in h) + ")" + ("" if rec["finite_length"] else " not zero by degree %d" % rec["degree_bound"])


def agree(rec):
    a = rec.get("agree")
    return "n/a (I1 needs finite length)" if a is None else ("yes" if a else "NO")


w("# EXP-002 results summary: primitive points over the Heisenberg enveloping algebra U(H)")
w()
w("Facts of one run of `run.py` (artifacts/results.json, artifacts/run.log), wall time %s s. No verdict: the coordinating session "
  "writes verdict.md. Tables are rows of (i, degree, rank). Instrument I1 is the exact Python library `code/uhlib` (Tor complex of the "
  "minimal resolution of the trivial right module); instrument I2 is Singular 4.3.2 Plural `mres` in WSL, with the degrees read from the "
  "generators of each syzygy module (not `betti()`), sharing no code with I1." % R.get("wall_seconds"))
w()

# ---------------------------------------------------------------- C0
c0 = C["C0"]
w("## C0 calibration: all_ok = %s" % c0["all_ok"])
w()
w("| Module | dim | Hilbert function | Table by I1 | Table by I2 | I1 = expected | I2 = expected | I1 = I2 | Hilbert recomputed from I2 table |")
w("|---|---|---|---|---|---|---|---|---|")
for r in c0["cases"]:
    w("| %s | %d | %s | %s | %s | %s | %s | %s | %s |" % (r["name"], r["total_dimension"], hf(r), tab(r["betti_I1"]), tab(r["betti_I2"]),
                                                          r["I1_matches_expected"], r["I2_matches_expected"], agree(r),
                                                          r.get("hilbert_consistent_with_I2_table")))
w()
w("Kostant modules L(p,q), p <= 4: all 15 were built (q = 0 and q >= 1) as the U(H)-submodule of V4^(p-q) (x) (Lambda^2 V4)^q generated by the "
  "sl_2-span of the highest weight vector w^(p-q) (x) (w^a)^q (construction in `code/uhlib/kostant.py`); the dimension equals the Weyl "
  "dimension (p-q+1)(q+1)(p+2)(p+q+3)/6 in every case: %s; the module satisfies the defining relations of U(H) in every case: %s; the "
  "module rebuilt from its extracted presentation has the same Hilbert function: %s. I1 ran on the module from the sp_4 construction and I2 on "
  "its extracted presentation (generators and minimal relations), so the two instruments were fed different objects that must agree."
  % (all(r.get("dimension_matches_weyl", True) for r in c0["cases"]), all(r.get("module_is_UH_module", True) for r in c0["cases"]),
     all(r.get("rebuilt_from_presentation_same_hilbert", True) for r in c0["cases"])))
w()
w("Relation degrees of the extracted presentations (all minimal relations of L(p,q) sit in one degree, as Table F states): "
  + "; ".join("L(%s) %s" % (r["name"][2:-1], r["presentation_relation_degrees"]) for r in c0["cases"] if r["name"].startswith("L(")))
w()

# ---------------------------------------------------------------- C1
c1 = C["C1"]
w("## C1: U/U(x^2, y^2) over QQ and GF(32003)")
w()
for r in c1["fields"]:
    w("- %s: Hilbert function %s (hand derivation (1,2,2,2,1): %s); table by I1 %s; by I2 %s; agreement %s; equals the primitive pure table "
      "(1,2,2,1) on (0,2,6,8): %s; wall %s s (I1) and %s s (I2)." % (
          r["field"], hf(r), r["hilbert_equals_hand_derivation"], tab(r["betti_I1"]), tab(r["betti_I2"]), agree(r),
          r["table_equals_primitive_pure"], r["seconds_I1"], r.get("seconds_I2")))
w()
w("Graded pieces of the left ideal I = U(x^2, y^2) over QQ, reduced row echelon basis in the PBW monomials x^a y^b z^c, and the line-by-line "
  "comparison with the hand derivation of hypothesis.md:")
w()
q = [r for r in c1["fields"] if r["field"] == "QQ"][0]
for d in ("2", "3", "4", "5"):
    p = q["ideal_pieces"][d]
    w("- Degree %s: dim U_%s = %d; dim I_%s by the machine = %d (hand: %s). Hand elements listed in hypothesis.md: %d, spanning dimension %d; "
      "every hand element lies in the machine ideal: %s; hand span equals the machine piece: %s." % (
          d, d, p["dim_U_d"], d, p["dimension"], {"2": 2, "3": 4, "4": 8, "5": 12}[d], p["hand_elements"], p["hand_dimension"],
          p["hand_elements_in_ideal"], p["hand_span_equals_ideal_piece"]))
    for row in p["basis_rows"]:
        w("    - " + row)
w()
w("Resulting dim M_d = dim U_d - dim I_d: degrees 2, 3, 4, 5 give %s (hand: 2, 2, 1, 0); the Hilbert function over QQ is %s."
  % (", ".join(str(q["ideal_pieces"][d]["dim_U_d"] - q["ideal_pieces"][d]["dimension"]) for d in ("2", "3", "4", "5")), hf(q)))
w()
w("The three degree-5 elements -4x^2yz + 2xz^2, -5x^2yz + 4xz^2, x^2yz - 2xz^2 (coordinates on x^2yz, xz^2): rank by field: %s."
  % ", ".join("%s: %d" % (k, v) for k, v in c1["degree5_three_elements"]["rank_by_field"].items()))
w()

# ---------------------------------------------------------------- C2
c2 = C["C2"]
w("## C2: U/U(x^2, y^2) over GF(2^k) and GF(3^k), k = 1..4 (computed in those characteristics; the extension fields use a verified irreducible modulus)")
w()
w("| Field | Hilbert function through degree 14 | zero by degree 14 | Table by I2 | Hilbert recomputed from I2 table matches I1 | hand statement | observed |")
w("|---|---|---|---|---|---|---|")
for r in c2["fields"]:
    dims = r["hilbert_function_to_degree_bound"]
    if "GF(2" in r["field"]:
        stmt, obs = "dim M_4 = 2", "dim M_4 = %d" % dims[4]
    else:
        stmt, obs = "M_5 != 0", "dim M_5 = %d" % dims[5]
    w("| %s | %s | %s | %s | %s | %s | %s |" % (r["field"], "(" + ",".join(map(str, dims)) + ")", r["finite_length"], tab(r["betti_I2"]),
                                                r.get("hilbert_consistent_with_I2_table"), stmt, obs))
w()
w("The I1 Tor complex needs a finite length module, so no I1 table exists for these infinite modules; the I2 tables are checked against I1 "
  "through the Hilbert function recomputed from the table (last-but-one column).")
w()

# ---------------------------------------------------------------- C3
c3 = C["C3"]
w("## C3: U/U(x^e, y^e) over QQ")
w()
w("| e | Hilbert function | predicted pure Hilbert function equal | Table by I1 | Table by I2 | I1 = I2 | pure table (1,2,2,1) on (0,e,3e,4e) | in hypothesis range |")
w("|---|---|---|---|---|---|---|---|")
for r in c3["cases"]:
    w("| %d | %s | %s | %s | %s | %s | %s | %s |" % (r["e"], hf(r), r["hilbert_equals_pure_prediction"], tab(r["betti_I1"]), tab(r["betti_I2"]),
                                                       agree(r), r["table_equals_primitive_pure"], r["in_hypothesis_range"]))
w()
w("e = 2 is the case of C1, listed as a control (outside the hypothesis range e = 3..6).")
w()

# ---------------------------------------------------------------- C4
c4 = C["C4"]
w("## C4: cokernels of random 2 x 3 matrices of quadrics, seeds %s" % c4["seeds"])
w()
w("Predicted pure Hilbert function of (2,3,3,2) on (0,2,10,12): (%s). Each seed draws 3 relations of 2 quadrics (4 coefficients each, uniform in "
  "[0,32003)); the QQ module uses the same integer representatives as the lifted matrix." % ",".join(map(str, c4["pure_hilbert_function_predicted"])))
w()
w("Pure table (2,3,3,2) on (0,2,10,12) by both instruments: GF(32003) %d of 10, QQ (lifted) %d of 10." % (c4["hits_of_10"]["GF(32003)"], c4["hits_of_10"]["QQ"]))
w()
w("| Seed | Field | Hilbert function | Table by I1 | Table by I2 | I1 = I2 | pure table |")
w("|---|---|---|---|---|---|---|")
for r in c4["cases"]:
    w("| %d | %s | %s | %s | %s | %s | %s |" % (r["seed"], r["field"], hf(r), tab(r["betti_I1"]), tab(r["betti_I2"]), agree(r), r["table_equals_primitive_pure"]))
w()

# ---------------------------------------------------------------- C5
c5 = C["C5"]
w("## C5 (exploration): random pairs of quadrics over GF(2^k), GF(3^k), 20 seeds each; Hilbert function computed through degree 14")
w()
w("A pair is counted as finite when the quotient is zero in three consecutive degrees below the bound, otherwise as not finished (still nonzero at degree 14). "
  "The Betti table by I1 is computed for every finite quotient; I2 was run on up to 3 table hits per field.")
w()
w("| Field | finite | not finished by degree 14 | pairs with table (1,2,2,1) on (0,2,6,8) | Hilbert functions (count) | I1 tables of the finite ones (count) |")
w("|---|---|---|---|---|---|")
for s in c5["fields"]:
    hc = "; ".join("%s x%d" % (k, v) for k, v in s["hilbert_counts"].items())
    bc = "; ".join("%s x%d" % (tab(json.loads(k)), v) for k, v in s["betti_counts"].items()) or "none"
    w("| %s | %d | %d | %d | %s | %s |" % (s["field"], s["finite"], s["infinite_or_unfinished"], s["table_hits"], hc, bc))
w()
for s in c5["fields"]:
    for h in s["hits"]:
        w("- %s seed %d: Hilbert %s, I1 %s, I2 %s, agreement %s." % (s["field"], h["seed"], hf(h), tab(h["betti_I1"]), tab(h["betti_I2"]), agree(h)))
w()

# ---------------------------------------------------------------- C6
c6 = C["C6"]
w("## C6: duality on 20 finite length modules over GF(32003)")
w()
w("Construction: " + c6["construction"])
w()
w("Cases where the dual table equals the reverse of the table of M: %d of 20 by I1 (and by I2 where both ran). Seeds 6000..6009 are cokernels of "
  "2 x 3 matrices of quadrics, seeds 6010..6019 cokernels of 3 x 5 matrices of linear forms (truncated at degree 14 when infinite). "
  "The Hilbert function of a module whose dual is isomorphic to it up to shift is palindromic; the column below records that necessary condition." % c6["duality_holds_count"])
w()
w("| Seed | Kind | Hilbert function of M | Table of M (I1) | Table of M* (I1) | M* = reverse of M, I1 | M* = reverse of M, I2 | I1 = I2 on M, on M* | Hilbert palindromic |")
w("|---|---|---|---|---|---|---|---|---|")
for c in c6["cases"]:
    w("| %d | %s | %s | %s | %s | %s | %s | %s, %s | %s |" % (c["seed"], c["kind"], hf(c["module"]), tab(c["module"]["betti_I1"]), tab(c["dual"]["betti_I1"]),
                                                           c["dual_equals_reverse_I1"], c["dual_equals_reverse_I2"], agree(c["module"]),
                                                           agree(c["dual"]), c["hilbert_palindromic"]))
w()

# ---------------------------------------------------------------- instruments
every = []


def collect(o):
    if isinstance(o, dict):
        if "agree" in o and "betti_I1" in o:
            every.append(o)
        for v in o.values():
            collect(v)
    elif isinstance(o, list):
        for v in o:
            collect(v)


collect(C)
both = [r for r in every if r["agree"] is not None]
w("## Instrument agreement over the whole run")
w()
w("- Modules with both an I1 and an I2 table: %d; of these the tables agree in %d and differ in %d." % (len(both), sum(1 for r in both if r["agree"]), sum(1 for r in both if not r["agree"])))
cons = [r for r in every if r.get("hilbert_consistent_with_I2_table") is not None]
w("- Modules whose I2 table reproduces I1's Hilbert function through the dimension check: %d of %d." % (sum(1 for r in cons if r["hilbert_consistent_with_I2_table"]), len(cons)))
errs = [r["name"] for r in every if "I2_error" in r]
w("- I2 errors: %s." % (errs or "none"))
w()
w("## Deviations from the brief and the hypothesis, and notes")
w()
w("- The Singular script lists a zero vector as a generator of the last syzygy module when the module has no third syzygy (seen on the "
  "infinite modules of C2 in characteristic 2); the script skips zero vectors, so tables count nonzero generators only. The first run of C2 "
  "before this fix printed the artifact (3, -1000000, 1); it is not in results.json.")
w("- C3 also lists e = 2 (a control equal to C1); the hypothesis range is e = 3..6.")
w("- C4 over QQ uses the integer representatives in [0, 32003) of the GF(32003) draws as the lifted matrix.")
w("- C5: I2 was run on up to 3 table hits per field, not on every finite pair; I1 tables are computed for every finite pair. For infinite quotients "
  "only the Hilbert function through degree 14 exists.")
w("- C6: for the 2 x 3 quadric cokernels the table of M is symmetric under the reversal, so the reversal check is a weaker test there; the 3 x 5 "
  "cokernels have non-palindromic Hilbert functions (3,1,2) and a non-symmetric table, so M and M* are not isomorphic up to shift.")
w("- Coefficients over QQ are `fractions.Fraction`; GF(p^k) uses a polynomial representation with a brute-force verified irreducible modulus "
  "(`code/uhlib/fields.py`), and the same modulus is passed to Singular as `minpoly`.")
(HERE / "results-summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote results-summary.md", len(out), "lines")
