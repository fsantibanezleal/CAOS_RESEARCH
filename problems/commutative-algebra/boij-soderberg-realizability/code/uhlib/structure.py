"""Structure of finite length U(H)-modules and of left ideals in characteristic 2 (additions for EXP-003).

Weight grading: x has weight -1, y weight +1, z weight 0, so the PBW monomial x^a y^b z^c has weight b - a and every
left ideal generated by weight-homogeneous elements gives a weight-graded quotient (labels of `quotient_module`).
Characteristic 2: x^2, y^2, z are central, C = k[x^2, y^2, z] is a polynomial ring and U is free over C on 1, x, y, xy.
"""
from fractions import Fraction
from itertools import combinations, permutations, product
from math import comb, factorial

from . import algebra as A
from .fields import ExtField, PrimeField
from .linalg import Echelon, kernel, rank
