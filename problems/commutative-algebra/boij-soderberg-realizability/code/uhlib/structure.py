# ------------------------------------------------------------------ fields, subspaces
def field_elements(F):
    """All elements of a finite field object of fields.py (prime field or extension field)."""
    if isinstance(F, PrimeField):
        return list(range(F.p))
    if isinstance(F, ExtField):
        return [tuple(t) for t in product(range(F.p), repeat=F.k)]
    raise TypeError("finite fields only")


def gaussian_binomial(q, n, k):
    """Number of k-dimensional subspaces of GF(q)^n."""
    if q == 0:
        return 0
    num = den = 1
    for i in range(k):
        num *= q ** (n - i) - 1
        den *= q ** (i + 1) - 1
    return num // den


def rref_subspaces(F, n, k):
    """Every k-dimensional subspace of F^n exactly once, as the rows of its reduced row echelon basis."""
    elems = field_elements(F)
    for piv in combinations(range(n), k):
        free = [[j for j in range(piv[i] + 1, n) if j not in piv] for i in range(k)]
        slots = [(i, j) for i in range(k) for j in free[i]]
        for vals in product(elems, repeat=len(slots)):
            rows = [[F.zero] * n for _ in range(k)]
            for i in range(k):
                rows[i][piv[i]] = F.one
            for (i, j), v in zip(slots, vals):
                rows[i][j] = v
            yield rows


# ------------------------------------------------------------------ Hilbert function of U/(left ideal)
def _field_poly(F, p):
    return {m: coef(F, c) for m, c in p.items() if not F.is_zero(coef(F, c))}


def ideal_hilbert(F, gens, maxdeg):
    """dims[d] = dim (U/U(gens))_d for d = 0..maxdeg (homogeneous generators); no module structure is built."""
    gens = [_field_poly(F, g) for g in gens]
    gens = [(A.deg(next(iter(g))), g) for g in gens if g]
    dims = []
    for d in range(maxdeg + 1):
        B = list(A.monos(d))
        idx = {m: i for i, m in enumerate(B)}
        E = Echelon(F, len(B))
        for e, g in gens:
            if e > d:
                continue
            for u in A.monos(d - e):
                v = [F.zero] * len(B)
                for m, c in g.items():
                    for mm, kk in A.mono_mul(u, m):
                        i = idx[mm]
                        v[i] = F.add(v[i], F.mul(c, F.from_int(kk)))
                E.insert(v)
        dims.append(len(B) - E.rank())
    return dims


# ------------------------------------------------------------------ weights, kernels, socle
def weight_of(label):
    (_, (a, b, _)) = label
    return b - a


def weight_pieces(M):
    """{(weight, degree): dimension} of a module built by quotient_module (uses its monomial labels)."""
    out = {}
    for i, labs in enumerate(M.labels):
        for lab in labs:
            key = (weight_of(lab), M.lo + i)
            out[key] = out.get(key, 0) + 1
    return out


def predicted_weight_pieces(e):
    """The pieces predicted by D_q(n') of the context note: weight w, q = |w|, degree 2 n' + q."""
    out = {}
    for q in range(e):
        for n in range(0, 2 * e):
            dq = min(n + 1, e - q) if n <= e - 1 else max(0, 2 * e - 1 - q - n)
            if dq:
                for w in ((0,) if q == 0 else (q, -q)):
                    out[(w, 2 * n + q)] = dq
    return out


def kernel_of(M, which, d):
    """Basis (vectors of M_d) of the kernel of left multiplication by x, by y, or by both on M_d."""
    F = M.F
    i = d - M.lo
    if not 0 <= i < len(M.dims):
        return []
    if which == "x":
        images = M.X[i]
    elif which == "y":
        images = M.Y[i]
    else:
        images = [list(a) + list(b) for a, b in zip(M.X[i], M.Y[i])]
    tdim = len(images[0]) if images else 0
    if not images:
        return []
    return kernel(F, images, tdim)


def socle_by_weight(M):
    """{(degree, weight): dimension} of the socle (the common kernel of x and y)."""
    F = M.F
    out = {}
    for i, labs in enumerate(M.labels):
        d = M.lo + i
        for w in sorted({weight_of(lab) for lab in labs}):
            cols = [j for j, lab in enumerate(labs) if weight_of(lab) == w]
            images = [list(M.X[i][j]) + list(M.Y[i][j]) for j in cols]
            tdim = len(images[0]) if images else 0
            ker = kernel(F, images, tdim)
            if ker:
                out[(d, w)] = len(ker)
    return out


def class_of(M, poly, d):
    """Class in M_(d + deg poly) of poly . (a vector v of M_d is passed with d: here the class of poly . 1 for d = 0)."""
    assert d == 0 and M.dim(0) == 1
    F = M.F
    return M.act_poly(poly, 0, [F.one])


def g_element(e, a):
    """g_a of step 5 of the context note, as an integer polynomial in the PBW basis x^a y^b z^c:
    sum_j j! C(a,j) C(e,j) z^j y^(e-j-1) x^(a-j) (y-power to the left of the x-power, reordered by the product rule)."""
    out = {}
    for j in range(min(a, e - 1) + 1):
        coefficient = factorial(j) * comb(a, j) * comb(e, j)
        for m, k in A.mono_mul((0, e - j - 1, j), (a - j, 0, 0)):
            out[m] = out.get(m, 0) + coefficient * k
    return {m: c for m, c in out.items() if c}


def kernel_y_report(M, e):
    """Compare the kernel of y on M_e with the span of the classes z^c g_a (a < e, c >= 0), degree by degree."""
    F = M.F
    classes = {}  # degree -> list of vectors
    for a in range(e):
        ga = g_element(e, a)
        d = e - 1 + a
        v = class_of(M, ga, 0)
        while d <= M.hi:
            classes.setdefault(d, []).append((a, (d - (e - 1 + a)) // 2, v))
            v = M.act_z(d, v)
            d += 2
    per_degree = {}
    all_in_kernel, all_equal = True, True
    for i, n in enumerate(M.dims):
        d = M.lo + i
        ker = kernel_of(M, "y", d) if n else []
        vecs = classes.get(d, [])
        in_ker = all(not any(not F.is_zero(t) for t in M.act_y(d, v)) for _, _, v in vecs)
        span_rank = rank(F, [v for _, _, v in vecs], n) if vecs and n else 0
        equal = in_ker and span_rank == len(ker)
        per_degree[d] = {"dim": n, "kernel_y": len(ker), "classes_z_c_g_a": len(vecs), "span_rank": span_rank,
                         "classes_in_kernel": bool(in_ker), "equal": bool(equal)}
        all_in_kernel &= in_ker
        all_equal &= equal
    return {"kernel_y_equals_span_of_z_c_g_a": bool(all_equal), "classes_lie_in_kernel_y": bool(all_in_kernel),
            "per_degree": {str(d): r for d, r in per_degree.items()}}


# ------------------------------------------------------------------ k[z]-structure
def z_blocks(M):
    """Graded invariant factors of M as a k[z]-module: {(generator degree g, length L): multiplicity} for the
    summands k[z]/(z^L)(-g).  R(p,k) = rank of z^k on M_p; the number of summands generated in degree g with length
    at least k + 1 is R(g,k) - R(g-2,k+1)."""
    F = M.F
    rk = {}
    for i, n in enumerate(M.dims):
        p = M.lo + i
        vecs = [[F.one if t == j else F.zero for t in range(n)] for j in range(n)]
        k, d = 0, p
        while vecs and n:
            rk[(p, k)] = rank(F, vecs, M.dim(d))
            if rk[(p, k)] == 0:
                break
            vecs = [M.act_z(d, v) for v in vecs]
            k += 1
            d += 2

    def R(p, k):
        return rk.get((p, k), 0)

    ge = {}
    for i, n in enumerate(M.dims):
        g = M.lo + i
        for k in range(0, len(M.dims) + 2):
            c = R(g, k) - R(g - 2, k + 1)
            if c:
                ge[(g, k + 1)] = c
    out = {}
    for (g, L), c in ge.items():
        exact = c - ge.get((g, L + 1), 0)
        if exact:
            out[(g, L)] = exact
    return out


def predicted_z_blocks(e):
    """One summand k[z]/(z^(2e-1-a-b)) generated in degree a + b for each a, b < e (hypothesis of EXP-003, C2)."""
    out = {}
    for a in range(e):
        for b in range(e):
            key = (a + b, 2 * e - 1 - a - b)
            out[key] = out.get(key, 0) + 1
    return out


# ------------------------------------------------------------------ characteristic 2: the center and the derivation
_X, _Y = {(1, 0, 0): 1}, {(0, 1, 0): 1}


def central_subspace(F, polys, d):
    """Coefficient vectors c (on the given homogeneous degree-d polynomials) with sum c_i polys_i central in U(H)."""
    polys = [_field_poly(F, p) for p in polys]
    xf = {(1, 0, 0): F.one}
    yf = {(0, 1, 0): F.one}
    B = list(A.monos(d + 1))
    idx = {m: i for i, m in enumerate(B)}
    images = []
    for p in polys:
        v = [F.zero] * (2 * len(B))
        for off, g in ((0, xf), (len(B), yf)):
            left, right = A.poly_mul(F, g, p), A.poly_mul(F, p, g)
            for m, c in left.items():
                v[off + idx[m]] = F.add(v[off + idx[m]], c)
            for m, c in right.items():
                v[off + idx[m]] = F.sub(v[off + idx[m]], c)
        images.append(v)
    return kernel(F, images, 2 * len(B))


def _fpow(F, a, n):
    r = F.one
    for _ in range(n):
        r = F.mul(r, a)
    return r


def _cmul(F, p, q):
    out = {}
    for m1, c1 in p.items():
        for m2, c2 in q.items():
            m = tuple(x + y for x, y in zip(m1, m2))
            t = F.mul(c1, c2)
            out[m] = F.add(out[m], t) if m in out else t
    return {m: c for m, c in out.items() if not F.is_zero(c)}


def _cadd(F, p, q):
    out = dict(p)
    for m, c in q.items():
        out[m] = F.add(out[m], c) if m in out else c
    return {m: c for m, c in out.items() if not F.is_zero(c)}


_BASIS_C = ((0, 0), (1, 0), (0, 1), (1, 1))  # (a mod 2, b mod 2): the C-basis 1, x, y, xy of U in characteristic 2


def right_multiplication_matrix(F, f):
    """4 x 4 matrix over C = k[X, Y, Z] (X = x^2, Y = y^2, Z = z; entries are dicts {(s,t,c): coefficient}) of
    right multiplication u -> u f on the free C-module U with basis 1, x, y, xy (rows: images of the basis)."""
    assert F.char == 2
    rows = []
    for (a0, b0) in _BASIS_C:
        prod_ = A.poly_mul(F, {(a0, b0, 0): F.one}, f)
        row = [dict() for _ in range(4)]
        for (a, b, c), co in prod_.items():
            j = _BASIS_C.index((a % 2, b % 2))
            row[j] = _cadd(F, row[j], {(a // 2, b // 2, c): co})
        rows.append(row)
    return rows


def determinant_over_C(F, M):
    """Leibniz determinant of a square matrix of C-polynomials (dicts)."""
    n = len(M)
    total = {}
    for perm in permutations(range(n)):
        sign_odd = sum(1 for i in range(n) for j in range(i + 1, n) if perm[i] > perm[j]) % 2
        term = {(0, 0, 0): F.one}
        for i in range(n):
            term = _cmul(F, term, M[i][perm[i]])
            if not term:
                break
        if term:
            total = _cadd(F, total, term if not sign_odd else {m: F.neg(c) for m, c in term.items()})
    return total


def reduce_mod_linear_form(F, poly, lam):
    """poly in k[V0,V1,V2] reduced modulo the linear form sum lam_i V_i (lam != 0): V_i0 (the first i with lam_i != 0)
    is replaced by -lam_i0^-1 sum_(i != i0) lam_i V_i.  Returns (reduced dict over the exponents of the two remaining
    variables, the eliminated index)."""
    i0 = next(i for i in range(3) if not F.is_zero(lam[i]))
    others = [i for i in range(3) if i != i0]
    mu = F.neg(F.inv(lam[i0]))
    out = {}
    for mono, c in poly.items():
        m = mono[i0]
        base = tuple(mono[i] for i in others)
        for t in range(m + 1):  # (mu (lam_j Vj + lam_k Vk))^m = mu^m sum_t C(m,t) lam_j^t lam_k^(m-t) Vj^t Vk^(m-t)
            co = F.mul(F.mul(c, _fpow(F, mu, m)), F.from_int(comb(m, t)))
            co = F.mul(co, F.mul(_fpow(F, lam[others[0]], t), _fpow(F, lam[others[1]], m - t)))
            if F.is_zero(co):
                continue
            key = (base[0] + t, base[1] + m - t)
            out[key] = F.add(out[key], co) if key in out else co
    return {k: v for k, v in out.items() if not F.is_zero(v)}, i0


def derivation_data(F, gens):
    """The data of the derivation of EXP-003 for the subspace spanned by two independent quadrics f, g (char 2):
    the central combination c (a nonzero central quadric exists since dim C_2 + 2 > 4), whether both are central,
    and det of right multiplication by the non-central generator on U/Uc over R = C/(c) (zero, or its degree)."""
    assert F.char == 2
    fs = [_field_poly(F, g) for g in gens]
    cen = central_subspace(F, fs, 2)
    rec = {"central_dimension": len(cen), "both_central": len(cen) == 2}
    if not cen:
        return rec
    v = cen[0]
    c = {}
    for coefficient, g in zip(v, fs):
        for m, co in g.items():
            c[m] = F.add(c[m], F.mul(coefficient, co)) if m in c else F.mul(coefficient, co)
    c = {m: co for m, co in c.items() if not F.is_zero(co)}
    rec["c"] = {str(m): F.to_json(co) for m, co in sorted(c.items())}
    if rec["both_central"]:
        return rec
    # the non-central generator: a member of the pair independent of c
    f = fs[1] if F.is_zero(v[1]) else fs[0]
    # c is central so it has no xy component
    assert (1, 1, 0) not in c
    lam = [c.get((2, 0, 0), F.zero), c.get((0, 2, 0), F.zero), c.get((0, 0, 1), F.zero)]
    det = determinant_over_C(F, right_multiplication_matrix(F, f))
    red, i0 = reduce_mod_linear_form(F, det, lam)
    rec["f"] = {str(m): F.to_json(co) for m, co in sorted(f.items())}
    rec["det_over_C_is_zero"] = not det
    rec["det_is_zero"] = not red
    rec["eliminated_variable"] = "XYZ"[i0]
    rec["det_degree"] = None if not red else 2 * sum(next(iter(red)))
    return rec


# ------------------------------------------------------------------ the characteristic prediction of the context note
def ssyt_count_rectangle(rows, cols, n):
    """Number of semistandard tableaux of the rectangular shape rows x cols with entries <= n (hook content formula)."""
    num = Fraction(1)
    for i in range(rows):
        for j in range(cols):
            num *= Fraction(n + j - i, (cols - j - 1) + (rows - i - 1) + 1)
    assert num.denominator == 1
    return int(num)


def primes_up_to(n):
    return [p for p in range(2, n + 1) if all(p % q for q in range(2, int(p ** 0.5) + 1))]


def predicted_bad_primes(e, pmax, detail=False):
    """Primes <= pmax dividing (2e-1)! or a tableau count of the rectangle (e-w) x k with entries <= e,
    0 <= w < e, 1 <= k <= e (the condition of step 3 of the context note)."""
    counts = {}
    for w in range(e):
        for k in range(1, e + 1):
            counts[(w, k)] = ssyt_count_rectangle(e - w, k, e)
    bad, reasons = [], {}
    for p in primes_up_to(pmax):
        why = []
        if factorial(2 * e - 1) % p == 0:
            why.append("(2e-1)!")
        why += ["tableaux(w=%d,k=%d)=%d" % (w, k, c) for (w, k), c in sorted(counts.items()) if c % p == 0]
        if why:
            bad.append(p)
            reasons[p] = why
    return (bad, reasons, counts) if detail else bad
