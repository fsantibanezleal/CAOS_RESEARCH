"""The Kostant modules L(p,q) of sp_4 restricted to the Heisenberg nilradical, built concretely.

V4 has basis w, a, b, u (indices 0..3) of degrees 0, 1, 1, 2; the nilradical acts by
    x: w -> a, b -> u        y: w -> b, a -> -u        (z = [x,y] = 2 u d/dw)
and the Levi sl_2 on span(a, b) by  f: a -> b.  L(p,q) is the U(H)-submodule generated by the degree-0 part
(the sl_2-span of the highest weight vector) of the irreducible sp_4-module of highest weight (p,q) inside
V4^(tensor (p-q)) tensor (Lambda^2 V4)^(tensor q); all operators act as derivations on the tensor product.
The highest weight vector is w^(p-q) (x) (w^a)^q; it generates the irreducible sp_4-module, whose lowest
degree part is U(sl_2).hw = span(f^k hw, k = 0..q).  Degrees are shifted so that this part has degree 0.
"""
from .fields import QQ
from .module import GradedModule

V_DEG = (0, 1, 1, 2)
OPS = {
    "x": {0: {1: 1}, 2: {3: 1}},
    "y": {0: {2: 1}, 1: {3: -1}},
    "f": {1: {2: 1}},
}
PAIRS = [(0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)]
PAIR_INDEX = {pr: i for i, pr in enumerate(PAIRS)}


def _wedge(i, j):
    """(sign, pair index) of e_i ^ e_j, or None when it vanishes."""
    if i == j:
        return None
    return (1, PAIR_INDEX[(i, j)]) if i < j else (-1, PAIR_INDEX[(j, i)])


def _act_factor(op, kind, idx):
    """Action of op on one tensor factor (kind 'V' or 'L'); dict index -> integer coefficient."""
    table = OPS[op]
    out = {}
    if kind == "V":
        for dst, c in table.get(idx, {}).items():
            out[dst] = out.get(dst, 0) + c
        return out
    i, j = PAIRS[idx]
    for dst, c in table.get(i, {}).items():
        w = _wedge(dst, j)
        if w:
            out[w[1]] = out.get(w[1], 0) + c * w[0]
    for dst, c in table.get(j, {}).items():
        w = _wedge(i, dst)
        if w:
            out[w[1]] = out.get(w[1], 0) + c * w[0]
    return out


def _act_state(op, state, n1):
    out = {}
    for pos, idx in enumerate(state):
        kind = "V" if pos < n1 else "L"
        for dst, c in _act_factor(op, kind, idx).items():
            new = state[:pos] + (dst,) + state[pos + 1:]
            out[new] = out.get(new, 0) + c
    return {s: c for s, c in out.items() if c}


def _state_degree(state, n1):
    d = 0
    for pos, idx in enumerate(state):
        d += V_DEG[idx] if pos < n1 else V_DEG[PAIRS[idx][0]] + V_DEG[PAIRS[idx][1]]
    return d


def weyl_dimension(p, q):
    """dim of the irreducible sp_4-module of highest weight (p, q), p >= q >= 0."""
    return (p - q + 1) * (q + 1) * (p + 2) * (p + q + 3) // 6


class _Sparse:
    """Fully reduced sparse echelon basis over a field (vectors are dicts state -> field element)."""

    def __init__(self, F):
        self.F = F
        self.rows = {}

    def reduce(self, v):
        F = self.F
        v = dict(v)
        for p, row in self.rows.items():
            c = v.get(p)
            if c is not None and not F.is_zero(c):
                for k, e in row.items():
                    nv = F.sub(v.get(k, F.zero), F.mul(c, e))
                    if F.is_zero(nv):
                        v.pop(k, None)
                    else:
                        v[k] = nv
        return v

    def insert(self, v):
        F = self.F
        r = self.reduce(v)
        if not r:
            return False
        piv = min(r)
        inv = F.inv(r[piv])
        r = {k: F.mul(inv, e) for k, e in r.items()}
        for p, row in list(self.rows.items()):
            c = row.get(piv)
            if c is not None:
                for k, e in r.items():
                    nv = F.sub(row.get(k, F.zero), F.mul(c, e))
                    if F.is_zero(nv):
                        row.pop(k, None)
                    else:
                        row[k] = nv
        self.rows[piv] = r
        return True


def _apply(F, op, vec, n1):
    out = {}
    for state, c in vec.items():
        for s2, k in _act_state(op, state, n1).items():
            t = F.mul(c, F.from_int(k))
            out[s2] = F.add(out[s2], t) if s2 in out else t
    return {s: c for s, c in out.items() if not F.is_zero(c)}


def kostant_module(F, p, q, name=None):
    """L(p,q) over the field F (any characteristic; the construction has integer structure constants)."""
    assert 0 <= q <= p
    n1 = p - q
    hw = (0,) * n1 + (PAIR_INDEX[(0, 1)],) * q
    base = _state_degree(hw, n1)
    v = {hw: F.one}
    layer0 = _Sparse(F)
    while v:
        layer0.insert(v)
        v = _apply(F, "f", v, n1)
    layers = [layer0]
    while True:
        nxt = _Sparse(F)
        for row in layers[-1].rows.values():
            for op in ("x", "y"):
                img = _apply(F, op, row, n1)
                if img:
                    nxt.insert(img)
        if not nxt.rows:
            break
        layers.append(nxt)
    # all vectors of layer d share the tensor degree base + d
    dims = [len(L.rows) for L in layers]
    X, Y = [], []
    for d, L in enumerate(layers):
        piv_rows = [L.rows[pv] for pv in sorted(L.rows)]
        if d == len(layers) - 1:
            X.append([[] for _ in piv_rows])
            Y.append([[] for _ in piv_rows])
            continue
        N = layers[d + 1]
        npiv = sorted(N.rows)
        for table, op in ((X, "x"), (Y, "y")):
            imgs = []
            for row in piv_rows:
                img = _apply(F, op, row, n1)
                red = N.reduce(img)
                assert not red, "image outside the next layer"
                imgs.append([img.get(pv, F.zero) for pv in npiv])
            table.append(imgs)
    for d, L in enumerate(layers):
        for pv, row in L.rows.items():
            assert _state_degree(pv, n1) == base + d
    return GradedModule(F, 0, dims, X, Y, finished=True, name=name or "L(%d,%d)" % (p, q))


def expected_table(p, q):
    """Table F: beta = (q+1, p+2, p+2, q+1) on (0, p-q+1, p+q+3, 2p+4)."""
    return {(0, 0): q + 1, (1, p - q + 1): p + 2, (2, p + q + 3): p + 2, (3, 2 * p + 4): q + 1}


