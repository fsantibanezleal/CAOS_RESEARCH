"""Finite-dimensional graded left U(H)-modules: construction, presentation, duality.

A module is stored degree by degree: dims, and for each degree the images of the basis vectors under the
left multiplications by x and y (the matrices X and Y between consecutive degrees).  Left multiplication by a
PBW monomial x^a y^b z^c is x^a (y^b (z^c m)) with z acting as xy - yx.
"""
from fractions import Fraction

from . import algebra as A
from .linalg import Echelon, kernel


def coef(F, c):
    """Convert an int or a field element to a field element."""
    if isinstance(c, bool):
        raise TypeError
    if isinstance(c, int):
        return F.from_int(c)
    if isinstance(c, Fraction):
        return F.from_int(c.numerator) if c.denominator == 1 else F.mul(F.from_int(c.numerator), F.inv(F.from_int(c.denominator)))
    return c


def vzero(F, n):
    return [F.zero] * n


def vadd(F, u, v):
    return [F.add(a, b) for a, b in zip(u, v)]


def vscale(F, c, v):
    return [F.mul(c, a) for a in v]


class GradedModule:
    """dims[i] is the dimension of the degree lo + i piece; X[i][j], Y[i][j] the image (a vector of the
    degree lo + i + 1 piece) of the j-th basis vector of degree lo + i.  `finished` is False when the module
    was cut off at a degree bound while still nonzero (then the action is valid below the last degree only)."""

    def __init__(self, F, lo, dims, X, Y, finished=True, name=""):
        self.F = F
        self.lo = lo
        self.dims = list(dims)
        self.X = X
        self.Y = Y
        self.finished = finished
        self.name = name

    @property
    def hi(self):
        return self.lo + len(self.dims) - 1

    def dim(self, d):
        i = d - self.lo
        return self.dims[i] if 0 <= i < len(self.dims) else 0

    def total_dim(self):
        return sum(self.dims)

    def hilbert(self):
        return {self.lo + i: n for i, n in enumerate(self.dims) if n}

    def hilbert_list(self):
        """Dimensions from lo to the last nonzero degree."""
        out = list(self.dims)
        while out and out[-1] == 0:
            out.pop()
        return out

    def _op(self, table, d, v):
        F = self.F
        i = d - self.lo
        n_out = self.dim(d + 1)
        out = vzero(F, n_out)
        if n_out == 0 or not (0 <= i < len(self.dims)):
            return out
        for j, c in enumerate(v):
            if not F.is_zero(c):
                img = table[i][j]
                for t in range(n_out):
                    if not F.is_zero(img[t]):
                        out[t] = F.add(out[t], F.mul(c, img[t]))
        return out

    def act_x(self, d, v):
        return self._op(self.X, d, v)

    def act_y(self, d, v):
        return self._op(self.Y, d, v)

    def act_z(self, d, v):
        F = self.F
        a = self.act_x(d + 1, self.act_y(d, v))
        b = self.act_y(d + 1, self.act_x(d, v))
        return [F.sub(p, q) for p, q in zip(a, b)]

    def act_mono(self, m, d, v):
        a, b, c = m
        for _ in range(c):
            v = self.act_z(d, v)
            d += 2
        for _ in range(b):
            v = self.act_y(d, v)
            d += 1
        for _ in range(a):
            v = self.act_x(d, v)
            d += 1
        return v

    def act_poly(self, p, d, v):
        """Action of a homogeneous integer polynomial of U(H) on v in degree d; returns the vector in degree d + deg p."""
        F = self.F
        degs = {A.deg(m) for m in p}
        assert len(degs) <= 1, "act_poly needs a homogeneous polynomial"
        e = degs.pop() if degs else 0
        out = vzero(F, self.dim(d + e))
        for m, c in p.items():
            out = vadd(F, out, vscale(F, F.from_int(c), self.act_mono(m, d, v)))
        return out

    def check_relations(self):
        """True when [x,[x,y]] and [y,[x,y]] act as zero on every basis vector (the module is a U(H)-module)."""
        F = self.F
        for i, n in enumerate(self.dims):
            d = self.lo + i
            for j in range(n):
                e = [F.one if t == j else F.zero for t in range(n)]
                for g in (self.act_x, self.act_y):  # [g, z] v = g z v - z g v must vanish
                    lhs = g(d + 2, self.act_z(d, e))
                    rhs = self.act_z(d + 1, g(d, e))
                    if any(not F.is_zero(F.sub(a, b)) for a, b in zip(lhs, rhs)):
                        return False
        return True


def _free_basis(shifts, d):
    out = []
    for k, s in enumerate(shifts):
        if d - s >= 0:
            for m in A.monos(d - s):
                out.append((k, m))
    return out


def quotient_module(F, shifts, rels, maxdeg=24, name=""):
    """M = (sum_k U(-shifts[k])) / (left submodule generated by rels).

    rels: list of dicts {(k, mono): coefficient}, each homogeneous.  Builds degree by degree until the module
    vanishes for three consecutive degrees (finished) or maxdeg is reached (not finished).
    """
    rel_deg = []
    rels_f = []
    for g in rels:
        g = {key: coef(F, c) for key, c in g.items() if not F.is_zero(coef(F, c))}
        if not g:
            continue  # the zero relation
        degs = {shifts[k] + A.deg(m) for (k, m) in g}
        assert len(degs) == 1, "relation is not homogeneous"
        rel_deg.append(degs.pop())
        rels_f.append(g)
    lo = min(shifts) if shifts else 0
    maxshift = max(shifts) if shifts else 0
    ech, basis, nonpiv = {}, {}, {}
    dims = []
    d = lo
    zeros = 0
    finished = False
    while d <= maxdeg:
        B = _free_basis(shifts, d)
        idx = {b: i for i, b in enumerate(B)}
        E = Echelon(F, len(B))
        for g, e in zip(rels_f, rel_deg):
            if e > d:
                continue
            for u in A.monos(d - e):
                v = vzero(F, len(B))
                for (k, m), c in g.items():
                    for mm, kk in A.mono_mul(u, m):
                        i = idx[(k, mm)]
                        v[i] = F.add(v[i], F.mul(c, F.from_int(kk)))
                E.insert(v)
        ech[d], basis[d], nonpiv[d] = E, B, E.nonpivots()
        dims.append(len(nonpiv[d]))
        zeros = zeros + 1 if dims[-1] == 0 else 0
        if d >= maxshift and zeros >= 3:
            finished = True
            break
        d += 1
    if finished:
        while len(dims) > 1 and dims[-1] == 0:
            dims.pop()
    last = lo + len(dims) - 1
    X, Y = [], []
    for d in range(lo, last + 1):
        i = d - lo
        if d == last:
            X.append([[] for _ in range(dims[i])])
            Y.append([[] for _ in range(dims[i])])
            continue
        B1 = basis[d + 1]
        idx1 = {b: t for t, b in enumerate(B1)}
        cols = nonpiv[d]
        rx, ry = [], []
        for c in cols:
            k, m = basis[d][c]
            for gen, store in ((A.X, rx), (A.Y, ry)):
                v = vzero(F, len(B1))
                (gm,) = gen
                for mm, kk in A.mono_mul(gm, m):
                    t = idx1[(k, mm)]
                    v[t] = F.add(v[t], F.from_int(kk))
                store.append(ech[d + 1].coordinates(v))
        X.append(rx)
        Y.append(ry)
    return GradedModule(F, lo, dims, X, Y, finished=finished, name=name)


def ideal_module(F, gens, maxdeg=24, name=""):
    """U(H) / (left ideal generated by the homogeneous polynomials gens)."""
    rels = [{(0, m): c for m, c in g.items()} for g in gens]
    return quotient_module(F, [0], rels, maxdeg=maxdeg, name=name)


def truncate(M, D):
    """M modulo its part of degree >= D."""
    n = max(0, min(len(M.dims), D - M.lo))
    dims = M.dims[:n]
    X = [list(t) for t in M.X[:n]]
    Y = [list(t) for t in M.Y[:n]]
    if n:
        X[-1] = [[] for _ in range(dims[-1])]
        Y[-1] = [[] for _ in range(dims[-1])]
    return GradedModule(M.F, M.lo, dims, X, Y, finished=True, name=M.name + "|<%d" % D)


def minimal_generators(M):
    """A minimal homogeneous generating set: list of (degree, vector), a complement of xM + yM in each degree."""
    F = M.F
    gens = []
    for i, n in enumerate(M.dims):
        d = M.lo + i
        E = Echelon(F, n)
        if i > 0:
            for j in range(M.dims[i - 1]):
                for table in (M.X, M.Y):
                    E.insert(table[i - 1][j])
        for c in E.nonpivots():
            gens.append((d, [F.one if t == c else F.zero for t in range(n)]))
    return gens


def presentation(M):
    """(shifts, rels): generator degrees and a minimal generating set of the relations, so that
    M = (sum U(-shifts[k])) / (rels).  Needs a finite length module (finished)."""
    F = M.F
    gens = minimal_generators(M)
    shifts = [d for d, _ in gens]
    top = M.hi
    emax = max(top, max(shifts) if shifts else 0) + 3
    rels = []
    prev_ker = []  # kernel vectors (dicts over (k, mono)) of the previous degree
    for e in range(min(shifts) if shifts else 0, emax + 1):
        B = _free_basis(shifts, e)
        idx = {b: i for i, b in enumerate(B)}
        images = []
        for (k, m) in B:
            dk, vk = gens[k]
            images.append(M.act_mono(m, dk, vk))
        ker = kernel(F, images, M.dim(e))
        E = Echelon(F, len(B))
        for pk in prev_ker:
            for gen in (A.X, A.Y):
                (gm,) = gen
                v = vzero(F, len(B))
                for (k, m), c in pk.items():
                    for mm, kk in A.mono_mul(gm, m):
                        t = idx[(k, mm)]
                        v[t] = F.add(v[t], F.mul(c, F.from_int(kk)))
                E.insert(v)
        cur = []
        for kv in ker:
            as_dict = {B[i]: c for i, c in enumerate(kv) if not F.is_zero(c)}
            cur.append(as_dict)
            if E.insert(kv):
                rels.append(as_dict)
        prev_ker = cur
    return shifts, rels


def dual(M):
    """The graded dual M* = Hom_k(M, k) as a LEFT module through the antipode.

    M*_(-d) = (M_d)^*; Hom_k(M,k) is a right module by (f.u)(m) = f(u m), and the antipode S(x) = -x, S(y) = -y
    (S(z) = -z) turns it into the left module (u.f)(m) = f(S(u) m).  So x acts on M* by minus the transpose
    of the matrix of x: (x.f)(m) = -f(x m)."""
    F = M.F
    n = len(M.dims)
    lo = -M.hi
    dims = list(reversed(M.dims))
    X, Y = [], []
    # M*_(-(d+1)) -> M*_(-d); in the new list, index t corresponds to M degree hi - t
    for t in range(n):
        d_src = M.hi - t  # degree of M whose dual is this piece
        if t == n - 1:
            X.append([[] for _ in range(dims[t])])
            Y.append([[] for _ in range(dims[t])])
            continue
        d_tgt = d_src - 1
        rows_x, rows_y = [], []
        # basis vector j of (M_(d_src))^*: functional picking coordinate j; (x.f_j)(e_i) = -f_j(x e_i) = -X[d_tgt][i][j]
        for j in range(M.dim(d_src)):
            vx = [F.neg(M.X[d_tgt - M.lo][i][j]) for i in range(M.dim(d_tgt))]
            vy = [F.neg(M.Y[d_tgt - M.lo][i][j]) for i in range(M.dim(d_tgt))]
            rows_x.append(vx)
            rows_y.append(vy)
        X.append(rows_x)
        Y.append(rows_y)
    return GradedModule(F, lo, dims, X, Y, finished=M.finished, name="dual(" + M.name + ")")
