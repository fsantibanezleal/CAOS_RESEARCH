"""M3 preflight: the vertical far-corner blow-up (generator).

fa2b's CX^ vanishes exactly at {r = 1, tauA = tauB = s}, s = +-1 (both
pairs vertical at infinity, same side, same rate: A+ approaches B- across
the axis). Codimension 3; the center is two points times the epsB line.
Blow-up: (r - 1, tauA - s, tauB - s) = rhox (n1, n2, n3), rational
2-sphere (n1, n2, n3) = (2 t1, 2 t2, 1 - t1^2 - t2^2)/(1 + t1^2 + t2^2),
(t1, t2) in [-1, 1]^2 (covers the n3 >= -something hemisphere-plus; the
full sphere needs the antipodal chart, i.e. the SAME formulas with
(n1, n2, n3) negated, run as chart sign -1).

Extracts exactly (s = +1; s = -1 is the mirror, piece 9e):
  CX^2  = rhox^2 QXn / QXd      (the transverse quadratic)
  CS^2  =          QSn / QSd    (regular here: CS -> |1 - r| ... no:
                                 at the center CS = |dirA - dirB| = 0 too!
                                 tauA = tauB: CS vanishes: extract its
                                 power as found)
  T135, T154, T235, T236, Fh: each with its exact rhox-power.
Emits m3_gen.py (ring-generic, Pw powers, Frac rationals).
"""
import re
import sympy as sp
from pathlib import Path

rhox, t1, t2, eB = sp.symbols("rhox t1 t2 eB")

S = 1  # the s = +1 center; s = -1 is the mirror image
den = 1 + t1**2 + t2**2
n1 = 2 * t1 / den
n2 = 2 * t2 / den
n3 = (1 - t1**2 - t2**2) / den

r = 1 + rhox * n1
tA = S + rhox * n2
tB = S + rhox * n3
opA = 1 + tA**2
opB = 1 + tB**2
aA = (1 - tA**2) / opA
bA = 2 * tA / opA
aB = (1 - tB**2) / opB
bB = 2 * tB / opB

def split(name, expr):
    num, dn = sp.fraction(sp.cancel(sp.together(expr)))
    assert sp.simplify(dn.subs(rhox, 0)) != 0, (name, "den vanishes at 0")
    num = sp.expand(num)
    k = 0
    while True:
        quo, rem = sp.div(num, rhox, rhox)
        if rem == 0:
            num = sp.expand(quo)
            k += 1
        else:
            break
    assert sp.simplify(num.subs(rhox, 0)) != 0
    return k, num, sp.expand(dn)

quantities = {
    "CX2": (aA + r * aB)**2 + (bA - r * bB)**2,
    "CS2": (aA - r * aB)**2 + (bA - r * bB)**2,
    "T135": aB * (r * eB - bA) - aA * (eB - bB),
    "T154": aB * (r * eB - bA) + aA * (eB - bB),
    "T235": -aB * (r * eB + bA) + aA * (eB + bB),
    "T236": aA * (eB + bB) + aB * (r * eB + bA),
    "Fh": bA - r * bB,
    "Ah": aA,
    "Bh": aB,
}
results = {}
for nm, e in quantities.items():
    k, num, dn = split(nm, e)
    results[nm] = (k, num, dn)
    print(f"{nm}: rhox-power {k}, terms {len(num.as_ordered_terms())}")

# spot checks
import random
random.seed(11)
for _ in range(3):
    sub = {rhox: sp.Rational(random.randint(1, 6), 64),
           t1: sp.Rational(random.randint(-30, 30), 32),
           t2: sp.Rational(random.randint(-30, 30), 32),
           eB: sp.Rational(random.randint(1, 20), 32)}
    for nm, e in quantities.items():
        k, num, dn = results[nm]
        assert sp.simplify(e.subs(sub) - sub[rhox]**k * num.subs(sub) / dn.subs(sub)) == 0, nm
print("spot checks OK")

def emit(fh, name, poly):
    body = sp.printing.pycode(sp.horner(poly, wrt=rhox))
    body = body.replace("rhox", "R_").replace("t1", "Ta_") \
               .replace("t2", "Tc_").replace("eB", "E_")
    body = re.sub(r"\(([0-9]+)/([0-9]+)\)", r"Frac(\1, \2)", body)
    body = re.sub(r"([A-Za-z_][A-Za-z_0-9]*)\*\*([0-9]+)", r"Pw(\1, \2)", body)
    assert "**" not in body, ("residual **", name)
    fh.write(f"def {name}(R_, Ta_, Tc_, E_, Frac):\n    return " + body + "\n\n")

HERE = Path(__file__).resolve().parent
with open(HERE / "m3_gen.py", "w", encoding="utf-8") as fh:
    fh.write('"""Generated by verify-m3.py. Each X = rhox^k Xn/Xd; powers:\n')
    for nm, (k, _, _) in results.items():
        fh.write(f"  {nm}: k = {k}\n")
    fh.write('"""\n\ndef Pw(x, n):\n    r = x\n'
             '    for _ in range(n - 1):\n        r = r * x\n    return r\n\n')
    for nm, (k, num, dn) in results.items():
        emit(fh, nm + "n", num)
        emit(fh, nm + "d", dn)
print("m3_gen.py written")
