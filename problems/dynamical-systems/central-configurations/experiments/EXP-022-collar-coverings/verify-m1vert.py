"""M1-vert preflight: the vertical collision corner at body 1 (generator).

bicorner-same's CXc = |dirA + rr dirB^m| vanishes exactly at
{rr = 1, taua = taub = s}, s = +-1 (both pairs vertical at body 1, A+
approaching B- across the axis). s = +1 here; s = -1 is the mirror
(piece 9e). Sphere blow-up as in M3: (rr - 1, taua - 1, taub - 1) =
rhoy (n1, n2, n3), rational 2-sphere in (t1, t2); antipodal hemisphere =
chart sign -1 with the odd-hat convention.

Extracts each quantity's exact rhoy-power and emits m1vert_gen.py:
  CXc2, CSc2 (both quadratic), W1 = ca sb - cb sa, G5 = ca - rr cb,
  Fc = sa - rr sb, Kb = ca + rr cb, ca, cb, W2 = ca sb + cb sa.
"""
import re
import sympy as sp
from pathlib import Path

rhoy, t1, t2 = sp.symbols("rhoy t1 t2")

den = 1 + t1**2 + t2**2
n1 = 2 * t1 / den
n2 = 2 * t2 / den
n3 = (1 - t1**2 - t2**2) / den

rr = 1 + rhoy * n1
ta = 1 + rhoy * n2
tb = 1 + rhoy * n3
opa = 1 + ta**2
opb = 1 + tb**2
ca = (1 - ta**2) / opa
sa = 2 * ta / opa
cb = (1 - tb**2) / opb
sb = 2 * tb / opb

def split(name, expr):
    num, dn = sp.fraction(sp.cancel(sp.together(expr)))
    assert sp.simplify(dn.subs(rhoy, 0)) != 0, (name, "den vanishes at 0")
    num = sp.expand(num)
    k = 0
    while True:
        quo, rem = sp.div(num, rhoy, rhoy)
        if rem == 0:
            num = sp.expand(quo)
            k += 1
        else:
            break
    assert sp.simplify(num.subs(rhoy, 0)) != 0
    return k, num, sp.expand(dn)

quantities = {
    "CXc2": (ca + rr * cb)**2 + (sa - rr * sb)**2,
    "CSc2": (ca - rr * cb)**2 + (sa - rr * sb)**2,
    "W1": ca * sb - cb * sa,
    "W2": ca * sb + cb * sa,
    "G5": ca - rr * cb,
    "Kb": ca + rr * cb,
    "Fc": sa - rr * sb,
    "Ca": ca,
    "Cb": cb,
}
results = {}
for nm, e in quantities.items():
    k, num, dn = split(nm, e)
    results[nm] = (k, num, dn)
    print(f"{nm}: rhoy-power {k}, terms {len(num.as_ordered_terms())}")

import random
random.seed(13)
for _ in range(3):
    sub = {rhoy: sp.Rational(random.randint(1, 6), 64),
           t1: sp.Rational(random.randint(-30, 30), 32),
           t2: sp.Rational(random.randint(-30, 30), 32)}
    for nm, e in quantities.items():
        k, num, dn = results[nm]
        assert sp.simplify(e.subs(sub) - sub[rhoy]**k * num.subs(sub) / dn.subs(sub)) == 0, nm
print("spot checks OK")

def emit(fh, name, poly):
    body = sp.printing.pycode(sp.horner(poly, wrt=rhoy))
    body = body.replace("rhoy", "R_").replace("t1", "Ta_").replace("t2", "Tc_")
    body = re.sub(r"\(([0-9]+)/([0-9]+)\)", r"Frac(\1, \2)", body)
    body = re.sub(r"([A-Za-z_][A-Za-z_0-9]*)\*\*([0-9]+)", r"Pw(\1, \2)", body)
    assert "**" not in body, ("residual **", name)
    fh.write(f"def {name}(R_, Ta_, Tc_, Frac):\n    return " + body + "\n\n")

HERE = Path(__file__).resolve().parent
with open(HERE / "m1vert_gen.py", "w", encoding="utf-8") as fh:
    fh.write('"""Generated by verify-m1vert.py. Each X = rhoy^k Xn/Xd; powers:\n')
    for nm, (k, _, _) in results.items():
        fh.write(f"  {nm}: k = {k}\n")
    fh.write('"""\n\ndef Pw(x, n):\n    r = x\n'
             '    for _ in range(n - 1):\n        r = r * x\n    return r\n\n')
    for nm, (k, num, dn) in results.items():
        emit(fh, nm + "n", num)
        emit(fh, nm + "d", dn)
print("m1vert_gen.py written")
