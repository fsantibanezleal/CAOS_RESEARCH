"""Far-tube blow-up preflight: exact factor extraction + code generation.

Blow-up of fa2b's center {r = 1, tauA = tauB}: r = 1 + rhof*alpha,
tauA = tauB + rhof*beta, (alpha, beta) = (-(1-tauf^2), 2 tauf)/(1+tauf^2)
(alpha <= 0 covers r <= 1; the other half is the swap image).

For each needed quantity X in {CShat^2, T135, T235, Fh, CX2, T154, T236}
computes the exact num/den split (sympy cancel), asserts den is rhof-free,
extracts the declared rhof-power from the numerator by exact division, and
emits fartube_gen.py with ring-generic evaluators (num-hat and den), so
the chart code never hand-transcribes a coefficient:
  CS^2  = rhof^2 * Qn / Qd          (Qd a perfect square: emitted as is)
  T135  = rhof   * T135n / T135d
  T235  = rhof   * T235n / T235d
  Fh    = rhof   * Fhn / Fhd
  CX^2  =          CXn / CXd        (regular; vanishes only at its corner)
  T154, T236 nonzero at the center (checked; evaluated directly in-chart).
"""
import re
import sympy as sp

rhof, tauf, eB, tB = sp.symbols("rhof tauf eB tB")

opf = 1 + tauf**2
alpha = -(1 - tauf**2) / opf
beta = 2 * tauf / opf
r = 1 + rhof * alpha
tA = tB + rhof * beta
opA = 1 + tA**2
opB = 1 + tB**2
aA = (1 - tA**2) / opA
bA = 2 * tA / opA
aB = (1 - tB**2) / opB
bB = 2 * tB / opB

def split(name, expr, power):
    num, den = sp.fraction(sp.cancel(sp.together(expr)))
    # den is a product of (1 + tau^2)-type factors: rhof-dependent through
    # tauA = tauB + rhof beta, but NONVANISHING (>= 1): safe to invert
    # in-ring. Only require it nonzero at rhof = 0 so the numerator carries
    # the full rhof-order.
    assert sp.simplify(den.subs(rhof, 0)) != 0, (name, "den vanishes at 0")
    num = sp.expand(num)
    if power:
        quo, rem = sp.div(num, rhof**power, rhof)
        assert rem == 0, (name, "remainder nonzero")
        num = sp.expand(quo)
        assert sp.simplify(num.subs(rhof, 0)) != 0, (name, "hat vanishes at 0")
    return num, sp.expand(den)

CS2 = (aA - r * aB)**2 + (bA - r * bB)**2
Qn, Qd = split("CS2", CS2, 2)
print("Q: rhof-deg", sp.degree(Qn, rhof), "terms", len(Qn.as_ordered_terms()),
      "; den terms", len(Qd.as_ordered_terms()))

emA = r * eB - bA
emB = eB - bB
epA = r * eB + bA
epB = eB + bB
T135n, T135d = split("T135", aB * emA - aA * emB, 1)
T235n, T235d = split("T235", -aB * epA + aA * epB, 1)
Fhn, Fhd = split("Fh", bA - r * bB, 1)
CXn, CXd = split("CX2", (aA + r * aB)**2 + (bA - r * bB)**2, 0)
print("T135n", len(T135n.as_ordered_terms()), "T235n",
      len(T235n.as_ordered_terms()), "Fhn", len(Fhn.as_ordered_terms()),
      "CXn", len(CXn.as_ordered_terms()))

for nm, e in (("T154", aB * emA + aA * emB), ("T236", aA * epB + aB * epA)):
    v = sp.simplify(sp.together(e).subs(rhof, 0))
    assert v != 0, (nm, "unexpectedly vanishes at center")
print("T154, T236 nonzero at center: OK")

# numeric spot checks
import random
random.seed(3)
for _ in range(3):
    sub = {rhof: sp.Rational(random.randint(1, 8), 64),
           tauf: sp.Rational(random.randint(-30, 30), 32),
           tB: sp.Rational(random.randint(-30, 30), 32),
           eB: sp.Rational(random.randint(1, 20), 32)}
    assert sp.simplify(CS2.subs(sub) - (rhof**2 * Qn / Qd).subs(sub)) == 0
    assert sp.simplify((aB * emA - aA * emB).subs(sub) - (rhof * T135n / T135d).subs(sub)) == 0
    assert sp.simplify((bA - r * bB).subs(sub) - (rhof * Fhn / Fhd).subs(sub)) == 0
print("spot checks: OK")

def emit(fh, name, poly):
    body = sp.printing.pycode(sp.horner(poly, wrt=rhof))
    body = body.replace("rhof", "R_").replace("tauf", "Tf_") \
               .replace("eB", "E_").replace("tB", "Tb_")
    body = re.sub(r"\(([0-9]+)/([0-9]+)\)", r"Frac(\1, \2)", body)
    # IV/DV rings lack __pow__: symbol**n -> Pw(symbol, n)
    body = re.sub(r"([A-Za-z_][A-Za-z_0-9]*)\*\*([0-9]+)", r"Pw(\1, \2)", body)
    assert "**" not in body, ("residual **", name)
    fh.write(f"def {name}(R_, Tf_, E_, Tb_, Frac):\n    return " + body + "\n\n")

from pathlib import Path
OUT = str(Path(__file__).resolve().parent / "fartube_gen.py")
with open(OUT, "w", encoding="utf-8") as fh:
    fh.write('"""Generated by verify-fartube.py. num/den pairs, ring-generic.\n'
             'CS^2 = rhof^2 Qn/Qd; T135 = rhof T135n/T135d; T235 likewise;\n'
             'Fh = rhof Fhn/Fhd; CX^2 = CXn/CXd. No divisions inside.\n"""\n\n'
             'def Pw(x, n):\n'
             '    r = x\n'
             '    for _ in range(n - 1):\n'
             '        r = r * x\n'
             '    return r\n\n')
    for nm, poly in (("Qn", Qn), ("Qd", Qd), ("T135n", T135n),
                     ("T135d", T135d), ("T235n", T235n), ("T235d", T235d),
                     ("Fhn", Fhn), ("Fhd", Fhd), ("CXn", CXn), ("CXd", CXd)):
        emit(fh, nm, poly)
print("fartube_gen.py written")
