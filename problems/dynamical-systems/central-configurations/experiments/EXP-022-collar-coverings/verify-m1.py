"""M1 preflight: extractions for the quadruple-cluster blow-up.

M1 blows up bicorner-same's center {rr = 1, taua = taub}:
rr = 1 + rhoq alpha, taua = taub + rhoq beta, (alpha, beta) from tauq
(alpha <= 0 half; the rest is the swap image). With the identification
(ca, sa) <-> (aA, bA), (cb, sb) <-> (aB, bB), rr <-> r, the blow-up
factorizations of CSc, CXc, and Fc = sa - rr sb are EXACTLY fartube's
generated Qn/Qd, CXn/CXd, Fhn/Fhd (none involves eB). This script
verifies that reuse numerically and extracts the two NEW factors:
  W1 = ca sb - cb sa           = rhoq W1n / W1d   (the Wronskian)
  G5 = ca - rr cb              = rhoq G5n / G5d
and emits m1_gen.py. (K5hat = 2 G5hat + rr rhoa W1hat is composed
in-ring; id2A - id2B is evaluated directly, sound but wide near the face.)
"""
import re
import sympy as sp
from pathlib import Path

rhoq, tauq, tb = sp.symbols("rhoq tauq tb")

opq = 1 + tauq**2
alpha = -(1 - tauq**2) / opq
beta = 2 * tauq / opq
rr = 1 + rhoq * alpha
ta = tb + rhoq * beta
opa = 1 + ta**2
opb = 1 + tb**2
ca = (1 - ta**2) / opa
sa = 2 * ta / opa
cb = (1 - tb**2) / opb
sb = 2 * tb / opb

def split(name, expr, power):
    num, den = sp.fraction(sp.cancel(sp.together(expr)))
    assert sp.simplify(den.subs(rhoq, 0)) != 0, (name, "den vanishes at 0")
    num = sp.expand(num)
    quo, rem = sp.div(num, rhoq**power, rhoq)
    assert rem == 0, (name, "remainder nonzero")
    assert sp.simplify(quo.subs(rhoq, 0)) != 0, (name, "hat vanishes at 0")
    return sp.expand(quo), sp.expand(den)

W1n, W1d = split("W1", ca * sb - cb * sa, 1)
G5n, G5d = split("G5", ca - rr * cb, 1)
print("W1n terms", len(W1n.as_ordered_terms()), "G5n", len(G5n.as_ordered_terms()))

# verify the fartube reuse numerically: CSc^2 vs rhoq^2 Qn/Qd etc.
import importlib.util
HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("gen", HERE / "fartube_gen.py")
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)
Frac = sp.Rational
import random
random.seed(9)
for _ in range(3):
    sub = {rhoq: sp.Rational(random.randint(1, 8), 64),
           tauq: sp.Rational(random.randint(-30, 30), 32),
           tb: sp.Rational(random.randint(-30, 30), 32)}
    CSc2 = ((ca - rr * cb)**2 + (sa - rr * sb)**2).subs(sub)
    Qv = sp.Rational(gen.Qn(sub[rhoq], sub[tauq], 0, sub[tb], Frac)) / \
        sp.Rational(gen.Qd(sub[rhoq], sub[tauq], 0, sub[tb], Frac))
    assert sp.simplify(CSc2 - sub[rhoq]**2 * Qv) == 0, "Qn/Qd reuse FAILED"
    CXc2 = ((ca + rr * cb)**2 + (sa - rr * sb)**2).subs(sub)
    Xv = sp.Rational(gen.CXn(sub[rhoq], sub[tauq], 0, sub[tb], Frac)) / \
        sp.Rational(gen.CXd(sub[rhoq], sub[tauq], 0, sub[tb], Frac))
    assert sp.simplify(CXc2 - Xv) == 0, "CXn/CXd reuse FAILED"
    Fcv = (sa - rr * sb).subs(sub)
    Fv = sp.Rational(gen.Fhn(sub[rhoq], sub[tauq], 0, sub[tb], Frac)) / \
        sp.Rational(gen.Fhd(sub[rhoq], sub[tauq], 0, sub[tb], Frac))
    assert sp.simplify(Fcv - sub[rhoq] * Fv) == 0, "Fh reuse FAILED"
    W1v = (ca * sb - cb * sa).subs(sub)
    assert sp.simplify(W1v * W1d.subs(sub) - sub[rhoq] * W1n.subs(sub)) == 0
    G5v = (ca - rr * cb).subs(sub)
    assert sp.simplify(G5v * G5d.subs(sub) - sub[rhoq] * G5n.subs(sub)) == 0
print("fartube reuse + new extractions: spot checks OK")

def emit(fh, name, poly):
    body = sp.printing.pycode(sp.horner(poly, wrt=rhoq))
    body = body.replace("rhoq", "R_").replace("tauq", "Tf_").replace("tb", "Tb_")
    body = re.sub(r"\(([0-9]+)/([0-9]+)\)", r"Frac(\1, \2)", body)
    body = re.sub(r"([A-Za-z_][A-Za-z_0-9]*)\*\*([0-9]+)", r"Pw(\1, \2)", body)
    assert "**" not in body, ("residual **", name)
    fh.write(f"def {name}(R_, Tf_, Tb_, Frac):\n    return " + body + "\n\n")

with open(HERE / "m1_gen.py", "w", encoding="utf-8") as fh:
    fh.write('"""Generated by verify-m1.py: W1 = rhoq W1n/W1d, '
             'G5 = rhoq G5n/G5d.\n"""\n\n'
             'def Pw(x, n):\n'
             '    r = x\n'
             '    for _ in range(n - 1):\n'
             '        r = r * x\n'
             '    return r\n\n')
    for nm, poly in (("W1n", W1n), ("W1d", W1d), ("G5n", G5n), ("G5d", G5d)):
        emit(fh, nm, poly)
print("m1_gen.py written")
