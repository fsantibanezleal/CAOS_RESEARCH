    r = json.loads((ART / "results.json").read_text(encoding="utf-8"))
    out: list[str] = ["# EXP-007 results summary", "",
                      "Generated by `summarize.py` from `artifacts/results.json`; every value is an exact rational "
                      "string. Hypothesis: `hypothesis.md` (frozen). No verdict language here.", ""]
    d = r["data"]
    out += ["## Data", "", f"- `{d['file']}` under the data root, SHA-256 `{d['sha256']}` "
            f"({d['bytes']} bytes); equals the line of the archive's SHA256SUMS: {d['matches_sha256sums']}.",
            f"- environment: {json.dumps(r['environment'])}", ""]

    out += ["## R1: values with the authors' pricing", ""]
    rows = []
    for eid, v in r["R1"].items():
        rows.append([eid, str(v["routings"]), str(v["cost_good"]), str(v["minimizers"]), v["alpha_inst"], v["claimed"],
                     str(v["equal"]), str(v["feasible"]), "yes" if v["paths_match"] else "NO", f"{v['wall_s']}"])
