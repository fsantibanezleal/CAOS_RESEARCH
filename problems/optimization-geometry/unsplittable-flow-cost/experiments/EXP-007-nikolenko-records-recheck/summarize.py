"""Render results-summary.md from artifacts/results.json and the K17 state files (deterministic, exact strings).

    .venv/Scripts/python.exe .../EXP-007-nikolenko-records-recheck/summarize.py

Re-run it after the K17 frontier runs finish: the K17 section reads results.json when the run is complete and
the state files and logs while it is not. No verdict language: verdict.md is written by the coordinating session.
"""

from __future__ import annotations

import json
import re
from fractions import Fraction as F
from pathlib import Path

HERE = Path(__file__).resolve().parent
ART = HERE / "artifacts"


def fs(s) -> str:
    return str(s)


def dec(x: F, digits: int = 12) -> str:
    whole, rem = divmod(x.numerator, x.denominator)
    return f"{whole}.{(rem * 10**digits) // x.denominator:0{digits}d}"


def table(head: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(out)


def k17_state(eid: str) -> list[str]:
    log = ART / f"r4-{eid}.log"
    state = ART / f"r4-{eid}-state.jsonl"
    lines = []
    pid = None
    last = None
    if log.exists():
        text = log.read_text(encoding="utf-8").splitlines()
        for ln in text:
            m = re.search(r"start pid=(\d+)", ln)
            if m:
                pid = m.group(1)
        last = text[-1] if text else None
    tested = []
    if state.exists():
        for raw in state.read_text(encoding="utf-8").splitlines():
            if raw.strip():
                r = json.loads(raw)
                tested.append((r["index"], F(r["level"]), r["positive"], r["solves"], r["new_cuts"], r["seconds"]))
    lines.append(f"- log `artifacts/r4-{eid}.log`, state `artifacts/r4-{eid}-state.jsonl`; last process id seen in the log: {pid}")
    if last:
        lines.append(f"- last log line: `{last}`")
    if tested:
        pos = [t[1] for t in tested if t[2]]
        neg = [t[1] for t in tested if not t[2]]
        lines.append(f"- levels tested so far: {len(tested)}; largest level proved positive "
                     f"{max(pos) if pos else 'none yet'}" + (f" ({dec(max(pos))})" if pos else "")
                     + f"; smallest level proved not positive {min(neg) if neg else 'none yet'}"
                     + (f" ({dec(min(neg))})" if neg else ""))
        lines.append("")
        lines.append(table(["index", "level", "decimal", "positive", "LP solves", "new cuts", "seconds"],
                           [[str(i), str(lv), dec(lv), str(ok), str(s), str(c), f"{sec:.1f}"]
                            for i, lv, ok, s, c, sec in tested]))
    else:
        lines.append("- no level tested yet")
    return lines


