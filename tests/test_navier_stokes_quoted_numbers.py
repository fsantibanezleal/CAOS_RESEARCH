def test_wiki_page_8_numbers_come_from_the_code():
    from nslib import ab_schedule as A
    from nslib import cascade as C

    page = text(PROBLEM / "wiki/08-smoothness-versus-dissipation.md")
    s = A.ABSchedule()
    assert s.alpha_max(1) == pytest.approx(1.55e-4, rel=5e-3)
    assert s.alpha_max(2, favourable_angle=False) == pytest.approx(7.70e-7, rel=5e-3)
    assert s.stall_stage(1e-4) == 113
    assert A.ratio_needed_for(C.ALPHA0_CMZ / 2.0) == pytest.approx(0.675, abs=5e-3)
    assert A.derivatives_affordable(C.ALPHA0_CMZ / 2.0) == pytest.approx(0.006, abs=5e-4)

    for quoted in ("1.55\\times10^{-4}", "7.70\\times10^{-7}", "113", "0.675", "0.006"):
        assert quoted in page, f"{quoted} no longer appears in wiki page 8"


def test_wiki_page_6_ratio_interval_numbers_come_from_the_code():
    from nslib import cmz_budget as B

    page = text(PROBLEM / "wiki/06-where-the-published-threshold-comes-from.md")
    lo, hi = B.feasible_R_interval(0.05)
    assert lo == pytest.approx(1.143, abs=5e-4) and hi == pytest.approx(5.0, abs=5e-3)
    assert B.feasible_R_interval(0.10) is None
    closed = B.feasible_R_interval(B.ALPHA0)
    assert closed[1] - closed[0] < 1e-6
    assert closed[0] == pytest.approx(1.7559, abs=5e-4)

    for quoted in ("1.143", "5.000", "1.7559", "empty"):
        assert quoted in page, f"{quoted} no longer appears in wiki page 6"


def test_the_converse_bound_numbers_match_the_code():
    """The sharpened claim: one derivative caps the exponent at 1/480."""
    from nslib import ab_schedule as A

    page = text(PROBLEM / "wiki/08-smoothness-versus-dissipation.md")
    dossier = text(PROBLEM / "context/2026-09-16-smoothness-versus-dissipation.md")

    assert A.alpha_max_for_derivatives(1) == pytest.approx(1.0 / 480.0)
    assert A.gap_to_published_threshold(1, 1.0) == pytest.approx(22.2, rel=5e-2)
    assert A.gap_to_published_threshold(1, A.DELTA_PUBLISHED) == pytest.approx(177.9, rel=5e-2)

    for quoted in ("1/480=0.00208", "twenty-two times", "one hundred and seventy-eight"):
        assert quoted in page, f"{quoted} no longer appears in wiki page 8"
    for quoted in ("alpha < delta / (480 k)", "1/480 = 0.00208", "22 times", "178 times"):
        assert quoted in dossier, f"{quoted} no longer appears in the dossier"
