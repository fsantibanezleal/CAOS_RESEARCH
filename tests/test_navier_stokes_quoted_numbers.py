"""Every headline number quoted in prose must still be in the artifact it came from.

Verdicts and wiki pages quote numbers from result JSONs and from code. Those files are
edited by hand and the results are regenerated by runs, so the two drift silently: a rerun
moves a value, the prose keeps the old one, and the old one is what a reader quotes. This
guard pins the numbers that carry the conclusions of EXP-005 and of the smoothness-versus-
dissipation trade-off to their sources.

It deliberately checks the FORMATTED strings that appear in the prose, not just the values,
because the failure mode is prose that no longer matches, not arithmetic that stopped
working.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
PROBLEM = ROOT / "problems/analysis-pde/navier-stokes"
EXP005 = PROBLEM / "experiments/EXP-005-steered-cycle"
CODE = PROBLEM / "code"
if str(CODE) not in sys.path:
    sys.path.insert(0, str(CODE))


def load(name: str) -> dict:
    return json.loads((EXP005 / name).read_text(encoding="utf-8"))


def text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def test_exp005_part_b_numbers_match_the_flattened_run():
    d = load("result-B-flattened.json")
    m = d["main"]
    verdict = text(EXP005 / "verdict.md")

    assert m["landing_pde"] == pytest.approx(3.67e-4, rel=5e-3)
    assert m["gain_relative_error"] == pytest.approx(3.06e-6, rel=5e-3)
    assert m["hold_theta_relative_drift"] == pytest.approx(0.0036, rel=5e-2)
    assert d["endpoint_max_gap"] == pytest.approx(4.7e-4, rel=5e-2)
    assert d["all_pass"] is True

    for quoted in ("3.67e-04", "3.06e-06", "0.36 %", "4.7e-04"):
        assert quoted in verdict, f"{quoted} no longer appears in the verdict"


def test_exp005_part_b_sine_column_is_the_curvature_comparison():
    sine = load("result-B-sine.json")["main"]
    flat = load("result-B-flattened.json")["main"]
    # the whole point of the pair: same everything, worse only through curvature
    assert sine["landing_pde"] > 10 * flat["landing_pde"]
    assert sine["gain_relative_error"] > 100 * flat["gain_relative_error"]
    assert sine["landing_pde"] == pytest.approx(1.57e-2, rel=5e-2)
    assert "1.57e-02" in text(EXP005 / "verdict.md")


