"""Generate every table, figure fragment and quoted number of the first-interior-shell paper from the experiment records.

Inputs (under the bougard-joret experiments folder given by --exp):
  EXP-001-tree-strip/artifacts/certificate.json           tree orders, residual enumeration, order-six census
  EXP-002-next-shell/artifacts/certificate.json           the 75 shell constructions, cycle controls, order-six census
  EXP-002-next-shell/artifacts/independent-audit.json     NetworkX recomputation of the same objects
  the run.py, audit.py and proof.md files whose SHA-256 digests the records quote

Outputs (next to this script; all are overwritten):
  numbers.tex            \\newcommand macros for every count and digest the text quotes
  table-residual.tex     the labeled residual enumeration (Table 1)
  table-shell.tex        the 75 shell constructions (longtable)
  table-controls.tex     the eight complement-cycle controls
  table-damaged.tex      the damaged-edge controls by construction case, and the two order-six censuses
  table-positions.tex    the excess over the degree-sum bound at three known positions (formulas of the cited theorems)
  table-digests.tex      the SHA-256 digests quoted by the records, each checked against the file it names
  fig-lift.tex           the residual lift on one recorded case, drawn from its edge lists
  fig-grid.tex           the construction case at every (k, a) of the shell grid
  fig-trees.tex          trees per order generated by leaf augmentation
  fig-residual.tex       outcomes of the labeled residual enumeration per k
  fig-shortfall.tex      the shortfall of the second-line expression below the degree-sum bound

Every consistency condition the text relies on is asserted here; the script exits 1 with a message when one fails.
Usage: python make_tables.py [--exp <experiments folder>]
"""
import argparse
import hashlib
import json
import sys
from collections import Counter, defaultdict
from math import comb
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIFT_CASE = (7, 4)  # (k, a) drawn in fig-lift.tex: a Harary residual with an added complement matching
CASE_LABEL = {"complement-cycle": "cycle", "crown": "crown", "matching": "matching",
              "tree-strip": "path", "harary": "Harary"}
CASE_LETTER = {"complement-cycle": "C", "crown": "W", "matching": "M", "tree-strip": "P", "harary": "H"}


def fail(message):
    print("make_tables.py: " + message, file=sys.stderr)
    sys.exit(1)


def check(condition, message):
    if not condition:
        fail(message)


def lf_sha256(path):
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def write(name, text):
    (HERE / name).write_text(text, encoding="utf-8", newline="\n")


def fmt(x):
    return f"{x:,}".replace(",", "{,}")


def ceil_div(a, b):
    return -(-a // b)


def t_edges(n, a):
    q, r = divmod(n, a)
    return r * comb(q + 1, 2) + (a - r) * comb(q, 2)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exp", default=str(HERE.parents[2] / "problems" / "combinatorics" / "bougard-joret" / "experiments"))
    exp = Path(ap.parse_args().exp)
    e1 = exp / "EXP-001-tree-strip"
    e2 = exp / "EXP-002-next-shell"
    c1 = json.loads((e1 / "artifacts" / "certificate.json").read_text(encoding="utf-8"))
    c2 = json.loads((e2 / "artifacts" / "certificate.json").read_text(encoding="utf-8"))
    au = json.loads((e2 / "artifacts" / "independent-audit.json").read_text(encoding="utf-8"))

    # ------------------------------------------------------------------ statuses and digests
    check(c1["status"] == "passed" and c2["status"] == "PASS" and au["status"] == "PASS", "a record is not in the passed state")
    digests = []  # (role, recorded digest, file it names)
    digests.append(("EXP-001 run.py (recorded in its certificate)", c1["script_sha256"], e1 / "run.py"))
    for name, value in sorted(c2["source_sha256"].items()):
        digests.append((f"{name} (recorded in the EXP-002 certificate)", value, exp / name))
    digests.append(("EXP-001 certificate, line endings normalised (in the EXP-002 certificate)",
                    c2["exp001_baseline_lf_sha256"], e1 / "artifacts" / "certificate.json"))
    digests.append(("EXP-002 audit.py (recorded in the recomputation output)", au["audit_source_sha256"], e2 / "audit.py"))
    digests.append(("EXP-002 proof.md (recorded in the recomputation output)", au["proof_sha256"], e2 / "proof.md"))
    digests.append(("EXP-002 certificate (recorded in the recomputation output)", au["certificate_sha256"],
                    e2 / "artifacts" / "certificate.json"))
    for name, value in sorted(au["checked_source_sha256"].items()):
        check(c2["source_sha256"][name] == value, f"the recomputation checked a different {name}")
    for role, recorded, path in digests:
        check(lf_sha256(path) == recorded, f"digest mismatch for {role}: {path}")
    check(au["networkx_version"] == "3.4.1", "NetworkX version of the recomputation changed")
    nx_version = au["networkx_version"]

    # ------------------------------------------------------------------ EXP-001: trees
    tree_rows = []
    for rec in c1["tree_orders"]:
        total = len(rec["trees"])
        stars = sum(1 for t in rec["trees"] if t["star_negative_control"])
        check(stars == 1 and total - stars == rec["valid_nonstar"], f"tree order {rec['order']}: counts disagree")
        check(all(t["alpha"] == (rec["order"] - 1 if t["star_negative_control"] else rec["order"] - 2) for t in rec["trees"]),
              f"tree order {rec['order']}: independence number")
        tree_rows.append((rec["order"], total, stars, rec["valid_nonstar"]))
    check([r[0] for r in tree_rows] == [4, 5, 6, 7, 8, 9], "tree orders are not 4 to 9")
    check([r[1] for r in tree_rows] == [2, 3, 6, 11, 23, 47], "tree counts differ from the unlabeled-tree sequence")
    check(sum(r[1] for r in tree_rows) == 92 and sum(r[3] for r in tree_rows) == 86, "tree totals")

    # ------------------------------------------------------------------ EXP-001: residual enumeration
    res_rows = []
    for rec in c1["residual_orders"]:
        k = rec["k"]
        n = k + 1
        edge_sets = comb(comb(n, 2), k)
        cayley = (k + 1) ** (k - 1)  # labeled trees on k+1 vertices
        check(rec["residual_graphs"] == rec["nonstar_trees"] + rec["stars"] + rec["disconnected"], f"k={k}: classes do not sum")
        check(rec["nonstar_trees"] + rec["stars"] == cayley, f"k={k}: trees plus stars differ from (k+1)^(k-1)")
        check(rec["stars"] == k + 1, f"k={k}: the number of labeled stars is k+1")
        res_rows.append((k, edge_sets, rec["residual_graphs"], rec["assignments"], rec["nonstar_trees"], rec["stars"],
                         rec["disconnected"], cayley))
    check([r[0] for r in res_rows] == [3, 4, 5], "residual orders")
    check(c1["base_census"]["extremals"] == 60 and c1["base_census"]["labeled_graphs"] == 32768, "EXP-001 census")
    check(c2["order_six_census"] == {"complements_of_six_cycles": 60, "extremals": 60, "labeled_graphs": 32768}, "EXP-002 census")

    # ------------------------------------------------------------------ EXP-002: the 75 constructions
    cases = sorted(c2["cases"], key=lambda c: (c["k"], c["alpha"]))
    rows_nx = {(r["k"], r["alpha"]): r for r in au["cases"]}
    check(len(cases) == 75 and len(rows_nx) == 75, "the grid does not hold 75 constructions")
    check({(c["k"], c["alpha"]) for c in cases} == {(k, a) for k in range(3, 13) for a in range(2, k + 2)}, "grid keys")
    by_case = Counter(c["case"] for c in cases)
    eps_by_case = Counter(c["case"] for c in cases if c["epsilon"])
    for c in cases:
        k, a, n = c["k"], c["alpha"], c["n"]
        nx_row = rows_nx[(k, a)]
        check(n == a + k + 1, f"({k},{a}): order")
        check(len(c["edges"]) == ceil_div(k * n, 2), f"({k},{a}): edge count is not ceil(kn/2)")
        check(nx_row["edges"] == len(c["edges"]) and nx_row["n"] == n, f"({k},{a}): recomputation disagrees on size")
        check(nx_row["connectivity"] == k and nx_row["alpha"] == a, f"({k},{a}): recomputed connectivity or independence")
        check(nx_row["damaged_connectivity"] == k - 1, f"({k},{a}): damaged-edge connectivity is not k-1")
        check(sorted(c["degrees"]) == [k] * (n - c["epsilon"]) + [k + 1] * c["epsilon"], f"({k},{a}): degree pattern")
        check(c["direct_subset_and_cut_check"] == (n <= 16), f"({k},{a}): direct checks run exactly for n<=16")
        check(c["epsilon"] == (n * k) % 2, f"({k},{a}): epsilon")
        check(("base_connectivity" in nx_row) == (c["case"] == "harary"), f"({k},{a}): residual rows")
        if c["case"] == "harary":
            check(nx_row["base_connectivity"] == c["d"] == k - a, f"({k},{a}): base connectivity is not k-a")
            check(nx_row["residual_connectivity"] == c["d"], f"({k},{a}): residual connectivity is not k-a")
    summary = c2["summary"]
    check(summary == {"cycle_controls": 8, "damaged_edge_controls": 75, "direct_checks": 45, "graphs": 75,
                      "harary_cases": 36, "odd_degree_sum_cases": 15}, "EXP-002 summary")
    check(by_case == Counter({"harary": 36, "complement-cycle": 10, "matching": 10, "crown": 10, "tree-strip": 9}), "case counts")
    check(sum(eps_by_case.values()) == 15, "odd-degree-sum cases")
    orders = [c["n"] for c in cases]

    # ------------------------------------------------------------------ numbers.tex
    nums = {
        "NTrees": 92, "NStars": 6, "NNonstar": 86,
        "NGraphs": 75, "NDirect": summary["direct_checks"], "NHarary": summary["harary_cases"],
        "NOdd": summary["odd_degree_sum_cases"], "NCycleControls": summary["cycle_controls"],
        "NDamaged": summary["damaged_edge_controls"], "NCensus": 32768, "NExtremalSix": 60,
        "NCaseCycle": by_case["complement-cycle"], "NCaseCrown": by_case["crown"], "NCaseMatching": by_case["matching"],
        "NCasePath": by_case["tree-strip"], "NCaseHarary": by_case["harary"],
        "NOddMatching": eps_by_case["matching"], "NOddHarary": eps_by_case["harary"],
        "NOrderMin": min(orders), "NOrderMax": max(orders), "NEdgeMin": min(len(c["edges"]) for c in cases),
        "NEdgeMax": max(len(c["edges"]) for c in cases),
    }
    out = ["% generated by make_tables.py; do not edit"]
    out += [f"\\newcommand{{\\{k}}}{{{fmt(v) if isinstance(v, int) and v > 9999 else v}}}" for k, v in nums.items()]
    out.append(f"\\newcommand{{\\NXVersion}}{{{nx_version}}}")
    write("numbers.tex", "\n".join(out) + "\n")

    # ------------------------------------------------------------------ table-residual.tex
    lines = [r"\begin{table}[ht]", r"\centering\small", r"\setlength{\tabcolsep}{4pt}",
             r"\begin{tabular}{rrrrrrrr}", r"\toprule",
             r"$k$ & Edge sets & Residuals & Assignments & Nonstar trees & Stars & Disconnected & Labeled trees\\", r"\midrule"]
    for k, es, rg, asg, nt, st, dc, cay in res_rows:
        lines.append(f"{k} & {fmt(es)} & {fmt(rg)} & {fmt(asg)} & {fmt(nt)} & {st} & {dc} & {fmt(cay)}\\\\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\caption{Exact labeled residual enumeration [MV]. Edge sets: all $k$-edge subsets of the pairs of $k+1$ labeled vertices; residuals: those without an isolated vertex; assignments: all missing-neighbor assignments of the $k-1$ labeled vertices of $S$, summed over residuals, including rejected ones (they do not count unmarked extremal graphs); the last column is $(k+1)^{k-1}$, the number of labeled trees, which equals the nonstar trees plus the stars.}",
              r"\label{tab:residual}", r"\end{table}"]
    write("table-residual.tex", "\n".join(lines) + "\n")

    # ------------------------------------------------------------------ table-shell.tex
    cap = (r"The 75 constructions of the shell grid, one row per $(k,a)$ with $n=a+k+1$. Construction: the residual used "
           r"(cycle: complement of $C_n$; Harary: cycle power with a complement matching; matching: perfect matching on $k+1$ "
           r"vertices; path: $P_{k+1}$; crown: $K_{a,a}$ minus a perfect matching). Columns $\kappa(G)$, $\alpha(G)$ and "
           r"$\kappa(G-e)$ are recomputed with NetworkX " + nx_version + r" from the saved edge lists, where $e$ is the edge "
           r"deleted in the damaged-edge control; $g=k-a$ and $\kappa(H)$ are the residual requirement and the recomputed "
           r"connectivity of the augmented residual graph in the Harary rows; the last column marks the 45 constructions "
           r"of order at most 16 also checked by direct subset and vertex-deletion enumeration.")
    lines = [r"{\scriptsize\setlength{\tabcolsep}{3.4pt}", r"\begin{longtable}{rrrlrrrrrrrl}",
             r"\caption{" + cap + r"}\label{tab:shell75}\\", r"\toprule",
             r"$k$ & $a$ & $n$ & Construction & $\e(G)$ & $\varepsilon$ & $\kappa(G)$ & $\alpha(G)$ & $\kappa(G-e)$ & $g$ & $\kappa(H)$ & Direct\\",
             r"\midrule", r"\endfirsthead", r"\toprule",
             r"$k$ & $a$ & $n$ & Construction & $\e(G)$ & $\varepsilon$ & $\kappa(G)$ & $\alpha(G)$ & $\kappa(G-e)$ & $g$ & $\kappa(H)$ & Direct\\",
             r"\midrule", r"\endhead", r"\bottomrule", r"\endfoot"]
    for c in cases:
        r = rows_nx[(c["k"], c["alpha"])]
        g = c["d"] if c["case"] == "harary" else "--"
        kh = r["residual_connectivity"] if c["case"] == "harary" else "--"
        lines.append(f"{c['k']} & {c['alpha']} & {c['n']} & {CASE_LABEL[c['case']]} & {len(c['edges'])} & {c['epsilon']} & "
                     f"{r['connectivity']} & {r['alpha']} & {r['damaged_connectivity']} & {g} & {kh} & "
                     f"{'yes' if c['direct_subset_and_cut_check'] else 'no'}\\\\")
    lines += [r"\end{longtable}", r"}"]
    write("table-shell.tex", "\n".join(lines) + "\n")

    # ------------------------------------------------------------------ table-controls.tex
    controls = c2["controls"]
    check(len(controls) == 8 and len(au["cycle_controls"]) == 8, "cycle controls")
    lines = [r"\begin{table}[ht]", r"\centering\small", r"\begin{tabular}{lrrccc}", r"\toprule",
             r"Cycle lengths of $F$ & $n$ & $k=n-3$ & $\alpha(\overline F)=2$ & $\kappa(\overline F)\ge k$ & Both and all lengths $\ge5$\\",
             r"\midrule"]
    for c, a_ in zip(controls, au["cycle_controls"]):
        lengths = c["complement_cycle_lengths"]
        check(lengths == a_["cycle_lengths"] and c["alpha_two"] == a_["alpha_two"] and c["k_connected"] == a_["k_connected"],
              f"cycle control {lengths}: the two implementations disagree")
        predicted = all(x >= 5 for x in lengths)
        check((c["alpha_two"] and c["k_connected"]) == predicted, f"cycle control {lengths}: characterization")
        n = sum(lengths)
        lines.append(f"${'+'.join(map(str, lengths))}$ & {n} & {n - 3} & {'yes' if c['alpha_two'] else 'no'} & "
                     f"{'yes' if c['k_connected'] else 'no'} & {'yes' if predicted else 'no'}\\\\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\caption{The eight complement-cycle controls on $n$ vertices, where $F$ is the disjoint union of the listed cycles and $G=\overline F$ is its complement. The columns give independence number two, connectivity at least $k=n-3$ in both implementations (they agree on all eight), and whether all cycle lengths are at least five, which is the extremizer condition of Theorem~\ref{thm:cycles}; the last two columns agree in every row.}",
              r"\label{tab:controls}", r"\end{table}"]
    write("table-controls.tex", "\n".join(lines) + "\n")

    # ------------------------------------------------------------------ table-damaged.tex
    agg = defaultdict(lambda: {"n": 0, "dmin": 10 ** 9, "dmax": -1, "direct": 0, "kmin": 10 ** 9, "kmax": -1})
    for c in cases:
        r = rows_nx[(c["k"], c["alpha"])]
        a_ = agg[c["case"]]
        a_["n"] += 1
        a_["dmin"] = min(a_["dmin"], r["k"] - r["damaged_connectivity"])
        a_["dmax"] = max(a_["dmax"], r["k"] - r["damaged_connectivity"])
        a_["direct"] += c["direct_subset_and_cut_check"]
        a_["kmin"] = min(a_["kmin"], c["k"])
        a_["kmax"] = max(a_["kmax"], c["k"])
    lines = [r"\begin{table}[ht]", r"\centering\small", r"\begin{tabular}{lrrrr}", r"\toprule",
             r"Construction & Graphs & $k$ range & Drop of $\kappa$ & Rejected directly\\", r"\midrule"]
    for case in ("complement-cycle", "harary", "matching", "tree-strip", "crown"):
        a_ = agg[case]
        check(a_["dmin"] == a_["dmax"] == 1, f"{case}: damaged drop is not exactly one")
        lines.append(f"{CASE_LABEL[case]} & {a_['n']} & {a_['kmin']}--{a_['kmax']} & {a_['dmin']} & {a_['direct']} of {a_['n']}\\\\")
    lines += [r"\midrule",
              r"Order-six census, EXP-001 & \multicolumn{4}{p{0.46\textwidth}}{" + f"{fmt(c1['base_census']['labeled_graphs'])} labeled graphs, {c1['base_census']['extremals']} extremal, each tree-characterized" + r"}\\",
              r"Order-six census, EXP-002 & \multicolumn{4}{p{0.46\textwidth}}{" + f"{fmt(c2['order_six_census']['labeled_graphs'])} labeled graphs, {c2['order_six_census']['extremals']} extremal, equal to the {c2['order_six_census']['complements_of_six_cycles']} complements of six-cycles" + r"}\\",
              r"\bottomrule", r"\end{tabular}",
              r"\caption{Damaged-edge controls by construction case, and the two exhaustive order-six censuses. In each of the 75 constructions one edge at a vertex of degree $k$ is deleted; the recomputed connectivity falls by exactly one, from $k$ to $k-1$, in every case (column Drop of $\kappa$), and the direct deletion enumeration rejects the 45 graphs of order at most 16 (column Rejected directly). The censuses visit every labeled graph on six vertices.}",
              r"\label{tab:damaged}", r"\end{table}"]
    write("table-damaged.tex", "\n".join(lines) + "\n")

    # ------------------------------------------------------------------ table-positions.tex
    lines = [r"\begin{table}[ht]", r"\centering\small", r"\setlength{\tabcolsep}{4pt}", r"\begin{tabular}{rrrrrrrr}", r"\toprule",
             r" & \multicolumn{2}{c}{$(2k-1,k-1,k)$} & \multicolumn{2}{c}{$(2k,k-1,k)$} & \multicolumn{2}{c}{$(2k-1,2,k)$} & \\",
             r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
             r"$k$ & $f$ & excess & $f$ & excess & $f$ & excess & $\lceil k(2k-1)/2\rceil$\\", r"\midrule"]
    pos_rows = []
    for k in range(4, 13):
        deg_odd = ceil_div(k * (2 * k - 1), 2)
        f_dg = k * k - 1
        f_strip = k * k
        deg_even = k * k
        if k >= 9:  # f(2d+3,2,d+2)=d^2+4d+2 for d>=7, k=d+2
            d = k - 2
            f_nm = d * d + 4 * d + 2
            e_nm = f_nm - deg_odd
            check(e_nm == d // 2 - 1, f"k={k}: excess of the next-matching value")
            nm_cell = f"{f_nm} & {e_nm}"
        else:
            nm_cell = "-- & --"
        check(f_dg - deg_odd == k // 2 - 1, f"k={k}: boundary excess")
        check(f_strip - deg_even == 0, f"k={k}: strip excess")
        pos_rows.append(k)
        lines.append(f"{k} & {f_dg} & {f_dg - deg_odd} & {f_strip} & {f_strip - deg_even} & {nm_cell} & {deg_odd}\\\\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\caption{Excess of the exact minimum size over the degree-sum bound $\lceil nk/2\rceil$ at three positions, computed from the theorems they come from: the boundary value $k^2-1$ of Das and Gupta, the strip value $k^2$ proved here, and $d^2+4d+2$ with $d=k-2$ for $\alpha=2$ at order $2k-1$ (proved for $d\ge7$, hence $k\ge9$). The last column is the degree-sum bound at order $2k-1$; at order $2k$ it is $k^2$, so the strip excess is zero.}",
              r"\label{tab:positions}", r"\end{table}"]
    write("table-positions.tex", "\n".join(lines) + "\n")

    # ------------------------------------------------------------------ table-digests.tex
    lines = [r"\begin{table}[ht]", r"\centering\scriptsize", r"\setlength{\tabcolsep}{3pt}", r"\begin{tabular}{p{0.40\textwidth}p{0.55\textwidth}}",
             r"\toprule", r"File (where the digest is recorded) & SHA-256\\", r"\midrule"]
    for role, recorded, _path in digests:
        lines.append(role.replace("_", r"\_") + r" & \texttt{" + recorded[:32] + r"}\newline\texttt{" + recorded[32:] + r"}\\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\caption{The SHA-256 digests quoted by the saved certificates and by the independent recomputation. The table is generated by the script that also recomputes each digest from the file it names, with line endings normalised, and stops when one differs; all digests agree with the files.}",
              r"\label{tab:digests}", r"\end{table}"]
    write("table-digests.tex", "\n".join(lines) + "\n")

    # ------------------------------------------------------------------ fig-grid.tex
    colors = {"complement-cycle": "gray!15", "harary": "linknavy!20", "matching": "orange!30", "tree-strip": "green!25!gray!35",
              "crown": "red!20"}
    lines = [r"\begin{tikzpicture}[x=0.78cm,y=0.5cm,font=\scriptsize]"]
    for c in cases:
        x, y = c["k"], c["alpha"]
        lines.append(f"\\fill[{colors[c['case']]}] ({x - 0.5},{y - 0.5}) rectangle ({x + 0.5},{y + 0.5});")
        lines.append(f"\\draw[gray!60,line width=0.2pt] ({x - 0.5},{y - 0.5}) rectangle ({x + 0.5},{y + 0.5});")
        lines.append(f"\\node at ({x},{y}) {{{CASE_LETTER[c['case']]}}};")
        if c["epsilon"]:
            lines.append(f"\\fill[black] ({x + 0.3},{y + 0.3}) circle (1.1pt);")
    for k in range(3, 13):
        lines.append(f"\\node[below] at ({k},1.5) {{{k}}};")
    for a in range(2, 14):
        lines.append(f"\\node[left] at (2.5,{a}) {{{a}}};")
    lines.append(r"\node[below=9pt] at (7.5,1.5) {$k$};")
    lines.append(r"\node[rotate=90,above=18pt] at (2.5,7.5) {$a$};")
    lines.append(r"\end{tikzpicture}")
    write("fig-grid.tex", "\n".join(lines) + "\n")

    # ------------------------------------------------------------------ fig-lift.tex (one recorded Harary case)
    case = next(c for c in cases if (c["k"], c["alpha"]) == LIFT_CASE)
    check(case["case"] == "harary", "the drawn case must be a Harary residual")
    m = case["k"] + 1
    base = {tuple(e) for e in case["base_edges"]}
    resid = {tuple(e) for e in case["residual_edges"]}
    added = {tuple(e) for e in case["added_matching"]}
    check(resid == base | added and not (base & added), "the recorded residual is the base plus the added matching")
    misses = case["misses"]
    a = case["alpha"]
    check(len(misses) == a and len(set(misses)) == a, "the missing neighbors are distinct")
    lines = [r"\begin{tikzpicture}[scale=1.0,font=\scriptsize,vertex/.style={circle,draw=linknavy,fill=white,inner sep=1.6pt},"
             r"svertex/.style={rectangle,draw=black,fill=gray!15,inner sep=2pt}]"]
    import math
    for v in range(m):
        ang = 90 - 360 * v / m
        style = "vertex,very thick" if v in misses else "vertex"
        lines.append(f"\\node[{style}] (h{v}) at ({2.1 * math.cos(math.radians(ang)):.3f},{2.1 * math.sin(math.radians(ang)):.3f}) {{}};")
        lines.append(f"\\node[font=\\scriptsize] at ({2.55 * math.cos(math.radians(ang)):.3f},{2.55 * math.sin(math.radians(ang)):.3f}) {{{v}}};")
    for u, v in sorted(base):
        lines.append(f"\\draw[gray!70] (h{u})--(h{v});")
    for u, v in sorted(added):
        lines.append(f"\\draw[orange!80!black,very thick] (h{u})--(h{v});")
    for s, t_ in enumerate(misses):
        y = 1.8 - 1.2 * s
        lines.append(f"\\node[svertex,label=right:{{$s_{s}$}}] (s{s}) at (6.2,{y:.2f}) {{}};")
        lines.append(f"\\draw[dashed,red!65!black,thick] (s{s})--(h{t_});")
