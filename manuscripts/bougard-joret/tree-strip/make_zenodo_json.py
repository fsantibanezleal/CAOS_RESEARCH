"""Rewrite the version-dependent fields of zenodo.json from main.tex: title, version, date, description (the abstract).

Usage: python make_zenodo_json.py
The description is the abstract of main.tex with its TeX markup converted to Unicode; the script stops when a command it does not know is left over.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
VERSION = "0.05"
DATE = "2026-11-14"
VERSION_NOTES = (
    "Adds a related-work section (the proved cases of Bougard and Joret, the boundary theorem, the second line, the next-matching value), "
    "a section of algorithms with their costs, and a results section with the 75 shell constructions, the negative controls, the labeled residual "
    "enumeration and an ablation, with tables and figures generated by make_tables.py from the saved certificates. "
    "The shell parameter g = k - a replaces d, and the proof states the requirement m >= 2r + 4 of the cyclic-gap lemma. "
    "The statements and proofs of the three theorems are unchanged. The title is re-derived from the theorems."
)
MAP = [
    (r"\lceil", "\u2308"), (r"\rceil", "\u2309"), (r"\lfloor", "\u230a"), (r"\rfloor", "\u230b"),
    (r"\alpha", "\u03b1"), (r"\ge", "\u2265"), (r"\le", "\u2264"), (r"\varepsilon", "\u03b5"),
]


def tex_to_text(t):
    t = re.sub(r"%.*", "", t)
    t = t.replace("--", "\u2013")
    for a, b in MAP:
        t = t.replace(a, b)
    t = re.sub(r"\^2", "\u00b2", t)
    t = t.replace("$", "").replace("~", " ").replace("\\,", "")
    t = re.sub(r"\s+", " ", t).strip()
    if "\\" in t:
        sys.exit("make_zenodo_json.py: unconverted TeX in the abstract: " + t[t.index("\\"):][:40])
    return t


def main():
    main_tex = (HERE / "main.tex").read_text(encoding="utf-8")
    abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", main_tex, re.S).group(1)
    title_tex = re.search(r"\\title\{(.*?)\}\n\\author", main_tex, re.S).group(1)
    title = re.sub(r"\s+", " ", title_tex.replace("\\\\", " ")).replace("--", "-")
    title = title.replace("$k-1$", "k-1")
    z = json.loads((HERE / "zenodo.json").read_text(encoding="utf-8"))
    m = z["metadata"]
    m["title"] = title
    m["version"] = VERSION
    m["publication_date"] = DATE
    m["description"] = "<p>" + tex_to_text(abstract).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;") + "</p>"
    m["version_notes"] = VERSION_NOTES
    have = {r["identifier"] for r in m["related_identifiers"]}
    for doi in ("10.5281/zenodo.22343021", "10.5281/zenodo.24044537", "10.5281/zenodo.22831382"):
        if doi not in have:
            m["related_identifiers"].append({"identifier": doi, "relation": "references", "scheme": "doi"})
    (HERE / "zenodo.json").write_text(json.dumps(z, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    print("zenodo.json updated:", title, "| abstract words:", len(tex_to_text(abstract).split()))


if __name__ == "__main__":
    main()
