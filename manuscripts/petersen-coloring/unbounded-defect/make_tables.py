    cal = ring["validation"]
    check(cal["G52"]["fast_count"] == 0 and cal["ring_join_G52_2"]["fast_count"] > 0 and cal["K4_frame_G52"]["fast_count"] > 0, "calibration")
    check(all(v["agree_on_existence"] for v in cal.values()), "calibration routines disagree")
    pair_times = {k: v["seconds"] for k, v in r3pairs.items()}
    pair_checks = {k: v["check_seconds"] for k, v in r3pairs.items()}
    seq_times = {k: v["seconds"] for k, v in r3seq.items()}
    check(len(pair_times) == 10 and set(pair_times) == set(seq_times), "ten sampled pairs in both runs")
    check(all(v["status"] == "UNSAT" and v["verified"] for v in r3pairs.values()), "pair refutations")
    same_block = sum(1 for v in r3pairs.values() if v["blocks"][0] == v["blocks"][1])
    check(same_block == 5, "five pairs inside one block")
    pmin, pmax = min(pair_times.values()), max(pair_times.values())
    smin, smax = min(seq_times.values()), max(seq_times.values())
    M.add("nPairSolveMin", sec(pmin, 0))
    M.add("nPairSolveMax", sec(pmax, 0))
    M.add("nPairSeqMin", sec(smin, 0))
    M.add("nPairSeqMax", sec(smax, 0))
    M.add("nPairSolveMean", sec(statistics.mean(pair_times.values()), 0))
    M.add("nPairSolveSd", sec(statistics.stdev(pair_times.values()), 0))
    M.add("nPairSeqMean", sec(statistics.mean(seq_times.values()), 0))
    M.add("nPairSeqSd", sec(statistics.stdev(seq_times.values()), 0))
    M.add("nPairCheckMin", sec(min(pair_checks.values()), 0))
    M.add("nPairCheckMax", sec(max(pair_checks.values()), 0))
    M.add("nRthreeSolve", sec(R["R3"]["pd_le2"]["seconds"], 1))
    M.add("nRthreeCheck", sec(R["R3"]["pd_le2"]["drat_trim_seconds"], 1))
    M.add("nRthreeUpper", sec(r3up["R3_tries"][0]["seconds"], 1))
    M.add("nRtwoWitness", sec(R["R2"]["pd_le2"]["seconds"], 1))
    M.add("nRoneSolve", sec(R["R1"]["petersen"]["seconds"], 1))
    M.add("nRoneCheck", sec(R["R1"]["petersen"]["drat_trim_seconds"], 1))

    sz = {"A": pole_formula_size(nA, mA, dA), "B": pole_formula_size(nB, mB, dB)}  # kept vertices, internal edges, dangling ends
    check(sz["A"] == (1200, 34222) and sz["B"] == (1155, 32914), f"formula sizes of A and B {sz}")
    r1v, r1c = petersen_formula_size(102, 153)
    r2v, r2c = petersen_formula_size(204, 306, 2)
    r3v, r3c = petersen_formula_size(306, 459, 2)
    check((r1v, r1c) == (2295, 66710) and (r2v, r2c) == (5202, 134433) and (r3v, r3c) == (7803, 201651), "ring formula sizes")
