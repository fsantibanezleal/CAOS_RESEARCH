    check(uv == Counter({(0,): 11, (0, 3): 2, (0, 2): 1}), f"u|v distance sets {uv}")
    check(all(1 in k for k in other) and sum(other.values()) == 28, "the other pairings must always transmit distance 1")
    check(all(1 not in k for k in uv), "u|v pairing must never transmit 1")

    # EXP-010 distance sets
    dist_sets = Counter()
    per_e0 = Counter()
    for f in sorted(e10.glob("dist-G52-*.json")):
        d = load(f)
        for e, v in d["edges"].items():
            ds = v.get("dist_set")
            check(ds is not None, f"undecided entry in {f.name}")
            dist_sets[tuple(ds)] += 1
            per_e0[d["e0"]] += 1
    decided = sum(dist_sets.values())
    check(decided == 546 and dist_sets[(1,)] == 282, "EXP-010: 546 decided distance sets, 282 equal to {1}")
