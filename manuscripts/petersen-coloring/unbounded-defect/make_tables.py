    e12 = P / "experiments" / "EXP-012-conduction-rings" / "artifacts"
    e13 = P / "experiments" / "EXP-013-six-pole-charges" / "artifacts"
    e14 = P / "experiments" / "EXP-014-transfer-semigroups" / "artifacts"
    M = Macros()

    # ------------------------------------------------------------------ the 52-vertex counterexample
    edges52 = [tuple(map(int, ln.split())) for ln in (P / "data" / "gjmmm-52.edgelist").read_text().splitlines()
               if ln.strip() and not ln.startswith("#")]
    check(len(edges52) == 78, "G52 must have 78 edges")
    n52 = len({v for e in edges52 for v in e})
    check(n52 == 52, "G52 must have 52 vertices")
    # A = G52 - {0,3} - {1,9}; B = G52 - {2,7}
    nA, mA, dA = 52, 78 - 2, 4
