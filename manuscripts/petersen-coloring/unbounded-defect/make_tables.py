THOUSANDS = "{,}"


def fail(message):
    print("make_tables.py: " + message, file=sys.stderr)
    sys.exit(1)


def check(condition, message):
    if not condition:
        fail(message)


def num(n):
    """A count with thin-space free thousands separators, as text (inside or outside math)."""
    return f"{n:,}".replace(",", THOUSANDS) if isinstance(n, int) else str(n)


def sec(x, nd=1):
    return f"{x:,.{nd}f}".replace(",", THOUSANDS)


def set_tex(orbits):
    return r"$\{" + ",".join(ORB_TEX[o] for o in orbits) + r"\}$"


def load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def write(name, text):
    (HERE / name).write_text(text, encoding="utf-8", newline="\n")


class Macros:
    def __init__(self):
        self.items = {}

    def add(self, name, value):
        check(name not in self.items, f"duplicate macro {name}")
        self.items[name] = value

    def dump(self):
        lines = ["% Generated by make_tables.py from the experiment records. Do not edit."]
        for k, v in self.items.items():
            lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
        return "\n".join(lines) + "\n"


