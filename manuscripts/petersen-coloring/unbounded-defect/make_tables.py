    R = ring["rings"]
    check([R[k]["n"] for k in ("R1", "R2", "R3")] == [102, 204, 306], "ring orders")
    check(all(R[k]["girth"] == 5 and R[k]["edge_connectivity"] == 3 and R[k]["cyclic_cuts_below_4"] == [] for k in R), "ring structure")
    check(R["R1"]["petersen"]["status"] == "UNSAT" and R["R1"]["petersen"]["drat_trim_verified"] is True, "R1 refutation")
    check(R["R2"]["pd_le2"]["status"] == "SAT" and R["R2"]["pd_le2"]["checker_defect"] == 2, "R2 witness")
    check(R["R3"]["pd_le2"]["status"] == "UNSAT" and R["R3"]["pd_le2"]["drat_trim_verified"] is True, "R3 refutation")
    check(cuts["R1"]["cycle_separating_cut_below_4"] is None and cuts["R2"]["cycle_separating_cut_below_4"] is None, "exhaustive cuts")
